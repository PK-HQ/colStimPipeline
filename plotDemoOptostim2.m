    fprintf('Saved SVG: %s\n', svgFile);
    fprintf('Saved PNG: %s\n', pngFile);
    fprintf('Saved MAT structs (mapData, stimulationSummary): %s\n', matFile);

    outputFiles.svg = svgFile;
    outputFiles.png = pngFile;
    outputFiles.mat = matFile;
end


% ==============================================================
% Constrained ROI-only rigid registration of the measured activity
% ==============================================================

function [tform, transformInfo] = ...
        demoOptimizeRigidActivityTransform( ...
            fixedImage, movingImage, registrationMask, initialShiftPx)

    validMask = ...
        logical(registrationMask) & ...
        isfinite(fixedImage) & ...
        isfinite(movingImage);

    if nnz(validMask) < 500
        error( ...
            'plotDemoOptostim:TooFewRigidRegistrationPixels', ...
            'Only %d pixels are available for ROI rigid registration.', ...
            nnz(validMask));
    end

    fixedWork = double(fixedImage);
    movingWork = double(movingImage);

    fixedValues = fixedWork(validMask);
    movingValues = movingWork(validMask);

    fixedScale = std(fixedValues);
    movingScale = std(movingValues);

    if ~isfinite(fixedScale) || fixedScale <= eps
        fixedScale = 1;
    end

    if ~isfinite(movingScale) || movingScale <= eps
        movingScale = 1;
    end

    fixedWork = (fixedWork - mean(fixedValues)) ./ fixedScale;
    movingWork = (movingWork - mean(movingValues)) ./ movingScale;

    fixedWork(~isfinite(fixedWork)) = 0;
    movingWork(~isfinite(movingWork)) = 0;

    % Smooth only the copies used by the registration objective.
    fixedWork = imgaussfilt(fixedWork, 2.0);
    movingWork = imgaussfilt(movingWork, 2.0);

    initialParameters = [ ...
        initialShiftPx(1), ...
        initialShiftPx(2), ...
        0];

    parameterLimits = [60, 60, 15];

    optimizationOptions = optimset( ...
        'Display', 'off', ...
        'MaxIter', 180, ...
        'MaxFunEvals', 500, ...
        'TolX', 0.05, ...
        'TolFun', 1e-5);

    objectiveFunction = @(parameters) ...
        demoRigidRegistrationObjective( ...
            parameters, ...
            fixedWork, ...
            movingWork, ...
            registrationMask, ...
            parameterLimits);

    [optimizedParameters, objectiveValue] = fminsearch( ...
        objectiveFunction, ...
        initialParameters, ...
        optimizationOptions);

    optimizedParameters(1) = max( ...
        -parameterLimits(1), ...
        min(parameterLimits(1), optimizedParameters(1)));

    optimizedParameters(2) = max( ...
        -parameterLimits(2), ...
        min(parameterLimits(2), optimizedParameters(2)));

    optimizedParameters(3) = max( ...
        -parameterLimits(3), ...
        min(parameterLimits(3), optimizedParameters(3)));

    tform = demoMakeCenteredRigidTransform( ...
        size(fixedImage), ...
        optimizedParameters(1), ...
        optimizedParameters(2), ...
        optimizedParameters(3));

    transformInfo = demoDecomposeAffine2D(tform);
    transformInfo.objectiveValue = objectiveValue;
    transformInfo.optimizedParameters = optimizedParameters;
    transformInfo.nRegistrationPixels = nnz(validMask);
end


% ==============================================================
% Objective for constrained ROI-only rigid registration
% ==============================================================

function objectiveValue = demoRigidRegistrationObjective( ...
        parameters, fixedImage, movingImage, registrationMask, limits)

    excess = max(abs(parameters) - limits, 0);

    if any(excess > 0)
        objectiveValue = 1e3 + sum(excess.^2);
        return;
    end

    tform = demoMakeCenteredRigidTransform( ...
        size(fixedImage), ...
        parameters(1), ...
        parameters(2), ...
        parameters(3));

    transformedMoving = demoApplyGeometricTransform( ...
        movingImage, ...
        tform, ...
        size(fixedImage), ...
        'linear');

    [pearsonR, ~, nPixels] = demoPearsonRSquared( ...
        fixedImage, ...
        transformedMoving, ...
        registrationMask);

    if nPixels < 500 || ~isfinite(pearsonR)
        objectiveValue = 1e3;
        return;
    end

    % Preserve the sign of the relationship: maximize positive Pearson r,
    % rather than maximizing r-squared and accepting an inverted pattern.
    objectiveValue = 1 - pearsonR;
end


% ==============================================================
% Construct a rigid affine2d transform around the image center
% ==============================================================

function tform = demoMakeCenteredRigidTransform( ...
        imageSize, xShiftPx, yShiftPx, rotationDeg)

    centerX = (imageSize(2) + 1) / 2;
    centerY = (imageSize(1) + 1) / 2;

    angleRadians = rotationDeg * pi / 180;

    translateToOrigin = [ ...
        1 0 0; ...
        0 1 0; ...
       -centerX -centerY 1];

    rotationMatrix = [ ...
         cos(angleRadians) sin(angleRadians) 0; ...
        -sin(angleRadians) cos(angleRadians) 0; ...
         0 0 1];

    translateBack = [ ...
        1 0 0; ...
        0 1 0; ...
        centerX centerY 1];

    finalTranslation = [ ...
        1 0 0; ...
        0 1 0; ...
        xShiftPx yShiftPx 1];

    tform = affine2d( ...
        translateToOrigin * ...
        rotationMatrix * ...
        translateBack * ...
        finalTranslation);
end


% ==============================================================
% Estimate a geometric transform that moves only the measured activity
% ==============================================================

function [tform, transformInfo] = demoEstimateActivityTransform( ...
        fixedImage, movingImage, registrationMask, transformType)

    validMask = ...
        registrationMask & ...
        isfinite(fixedImage) & ...
        isfinite(movingImage);

    if nnz(validMask) < 500
        error( ...
            'plotDemoOptostim:TooFewRegistrationPixels', ...
            ['Only %d pixels are available for geometric registration ' ...
             'inside the registration region.'], ...
            nnz(validMask));
    end

    fixedWork = zeros(size(fixedImage), 'double');
    movingWork = zeros(size(movingImage), 'double');

    fixedValues = double(fixedImage(validMask));
    movingValues = double(movingImage(validMask));

    fixedStd = std(fixedValues);
    movingStd = std(movingValues);

    if ~isfinite(fixedStd) || fixedStd <= eps
        fixedStd = 1;
    end

    if ~isfinite(movingStd) || movingStd <= eps
        movingStd = 1;
    end

    fixedWork(validMask) = ...
        (fixedValues - mean(fixedValues)) / fixedStd;

    movingWork(validMask) = ...
        (movingValues - mean(movingValues)) / movingStd;

    % Smooth only the registration copies. The displayed data and final
    % Pearson calculation remain unsmoothed. A 2-pixel sigma suppresses
    % column-scale noise while retaining the broad spatial geometry.
    fixedWork = imgaussfilt(fixedWork, 2.0);
    movingWork = imgaussfilt(movingWork, 2.0);

    % Phase-correlation registration is more stable for this problem than
    % starting directly with the intensity optimizer. Fall back to
    % imregtform when imregcorr is unavailable or rejects the transform type.
    registrationSucceeded = false;

    if exist('imregcorr', 'file') == 2
        try
            tform = imregcorr( ...
                movingWork, ...
                fixedWork, ...
                transformType);
            registrationSucceeded = true;
        catch
            registrationSucceeded = false;
        end
    end

    if ~registrationSucceeded
        [optimizer, metric] = imregconfig('monomodal');

        if isprop(optimizer, 'MaximumIterations')
            optimizer.MaximumIterations = 500;
        end

        if isprop(optimizer, 'MinimumStepLength')
            optimizer.MinimumStepLength = 1e-6;
        end

        outputRef = imref2d(size(fixedImage));

        tform = imregtform( ...
            movingWork, ...
            outputRef, ...
            fixedWork, ...
            outputRef, ...
            transformType, ...
            optimizer, ...
            metric, ...
            'PyramidLevels', 4);
    end

    transformInfo = demoDecomposeAffine2D(tform);
    transformInfo.nRegistrationPixels = nnz(validMask);
end


% ==============================================================
% Apply a geometric transform to an activity map
% ==============================================================

function transformedImage = demoApplyGeometricTransform( ...
        inputImage, tform, outputSize, interpolationMethod)

    inputValid = isfinite(inputImage);
    inputFilled = double(inputImage);
    inputFilled(~inputValid) = 0;

    outputRef = imref2d(outputSize);

    transformedImage = imwarp( ...
        inputFilled, ...
        tform, ...
        interpolationMethod, ...
        'OutputView', outputRef, ...
        'FillValues', 0);

    transformedValid = imwarp( ...
        double(inputValid), ...
        tform, ...
        'linear', ...
        'OutputView', outputRef, ...
        'FillValues', 0);

    transformedImage(transformedValid < 0.5) = NaN;
end


% ==============================================================
% Decompose affine2d transform for reporting
% ==============================================================

function transformInfo = demoDecomposeAffine2D(tform)

    transformMatrix = tform.T;

    transformInfo.matrix = transformMatrix;
    transformInfo.translationPx = [transformMatrix(3,1), transformMatrix(3,2)];

    linearPart = transformMatrix(1:2,1:2);

    [U,S,V] = svd(linearPart);

    rotationMatrix = U * V';

    transformInfo.rotationDeg = atan2d(rotationMatrix(1,2), rotationMatrix(1,1));
    transformInfo.scaleX = S(1,1);
    transformInfo.scaleY = S(2,2);
end

