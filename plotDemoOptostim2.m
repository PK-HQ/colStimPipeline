function [figHandle, demoPlotData, outputFiles] = plotDemoOptostim2( ...
    currentBlockStruct, imagingData, bitmapData, ...
    columnarProducts, demoProducts, blockID, currentSessID, ...
    mainPath, monkeyName, chamberWanted, saveFlag)
%PLOTDEMOOPTOSTIM
% Two-panel demonstration figure for one optostimulation session.
%
% Panel A:
%   Full coregistered PCA response difference (90 deg - 0 deg), designed
%   targets, ROI outline, and the larger Gaussian footprint.
%
% Panel B:
%   Bandpassed 0%-contrast response difference:
%       mean(OptoStim 90 deg) - mean(OptoStim 0 deg)
%   with the same designed target overlays as Panel A, ROI, and the same
%   Gaussian footprint. Stabilization offsets are tested in both sign
%   conventions, and Pearson R^2 versus Panel A is reported outside it.
%
% All displayed spatial products are in current-session camera space.
% The PCA background is not masked by the ROI.

% =====================================================================
% Hardcoded response files for the current demo session
% =====================================================================

integratedResponseFile = ...
    'Y:\Chip\Chip20230906\run2\M28D20230906R2StabIntgS004E023.mat';

trialStructureFile = ...
    'Y:\Chip\Chip20230906\run2\M28D20230906R2TS.mat';

stabilizationFile = ...
    'Y:\Chip\Chip20230906\run2\M28D20230906R2StabCfg.mat';

fprintf('Running plotDemoOptostim2 version 2026-06-29-coreg-layout-v11\n');

% =====================================================================
% 1. Orientation lookup
% =====================================================================

% Use imagingData.ortpca directly for the displayed PCA background.
% columnarProducts.VERpca is already multiplied by the ROI/SNR mask inside
% generateBitmap, so it cannot show activity outside that mask.
%
% Do not use ndims(...) here: MATLAB drops trailing singleton dimensions,
% so a valid 512x512xNortx1 array reports ndims == 3.
if ~isfield(imagingData, 'ortpca') || ...
        isempty(imagingData.ortpca) || ...
        size(imagingData.ortpca,1) ~= size(imagingData.ortpca,2) || ...
        size(imagingData.ortpca,4) < blockID

    error( ...
        'plotDemoOptostim:MissingFullPCA', ...
        ['imagingData.ortpca is unavailable or does not contain ' ...
         'blockID %d. Size found: [%s].'], ...
        blockID, num2str(size(imagingData.ortpca)));
end

pcaOrts = squeeze(imagingData.orts(1,:,blockID));
pcaOrts = pcaOrts(:)';

demoOrts = demoProducts.orts(:)';

coregOrts = squeeze(bitmapData.orts(1,:,blockID));
coregOrts = coregOrts(:)';

pcaIdx0 = demoFindOrientationIndex( ...
    pcaOrts, 0, 'full imaging PCA', currentSessID);

pcaIdx90 = demoFindOrientationIndex( ...
    pcaOrts, 90, 'full imaging PCA', currentSessID);

if size(imagingData.ortpca,3) < max([pcaIdx0 pcaIdx90])
    error( ...
        'plotDemoOptostim:MissingFullPCASlices', ...
        ['imagingData.ortpca has %d orientation slices, but indices ' ...
         '%d and %d were requested.'], ...
        size(imagingData.ortpca,3), pcaIdx0, pcaIdx90);
end

demoIdx0 = demoFindOrientationIndex( ...
    demoOrts, 0, 'demo bitmap', currentSessID);

demoIdx90 = demoFindOrientationIndex( ...
    demoOrts, 90, 'demo bitmap', currentSessID);

coregIdx0 = demoFindOrientationIndex( ...
    coregOrts, 0, 'coregistered bitmap', currentSessID);

coregIdx90 = demoFindOrientationIndex( ...
    coregOrts, 90, 'coregistered bitmap', currentSessID);

% =====================================================================
% 2. Reference-session PCA maps
% =====================================================================

% IMPORTANT: use the unmasked PCA-denoised responses from imagingData.
% VERpca is already ROI/SNR masked upstream and therefore cannot display
% the full field outside the ROI outline.
pca0Reference = double( ...
    imagingData.ortpca(:,:,pcaIdx0,blockID));

pca90Reference = double( ...
    imagingData.ortpca(:,:,pcaIdx90,blockID));

if ~any(isfinite(pca0Reference(:)))
    error( ...
        'plotDemoOptostim:EmptyPCA0', ...
        'Session %d: 0-degree PCA map has no finite pixels.', ...
        currentSessID);
end

if ~any(isfinite(pca90Reference(:)))
    error( ...
        'plotDemoOptostim:EmptyPCA90', ...
        'Session %d: 90-degree PCA map has no finite pixels.', ...
        currentSessID);
end

% =====================================================================
% 3. Current-camera column maps
% =====================================================================

columnMap0Current = double( ...
    bitmapData.columnarbitmapCoreg(:,:,coregIdx0,blockID));

columnMap90Current = double( ...
    bitmapData.columnarbitmapCoreg(:,:,coregIdx90,blockID));

if ~isequal(size(columnMap0Current), size(columnMap90Current))
    error( ...
        'plotDemoOptostim:CoregBitmapSizeMismatch', ...
        ['Session %d: 0-degree and 90-degree coregistered ' ...
         'column maps have different dimensions.'], ...
        currentSessID);
end

currentCameraRef = imref2d(size(columnMap0Current));

% =====================================================================
% 4. Warp PCA into current-session camera space
% =====================================================================

[pca0Current, pca90Current, validPcaMask] = ...
    demoWarpPcaToCurrentCamera( ...
        pca0Reference, ...
        pca90Reference, ...
        bitmapData, ...
        blockID, ...
        currentCameraRef);

% Keep the full coregistered PCA field. The ROI is displayed only as an
% outline and is not used to mask or multiply the PCA response.
pcaDifference = pca90Current - pca0Current;

% =====================================================================
% 5. Warp ROI into current-session camera space
% =====================================================================

if ~isfield(imagingData, 'nanmask') || ...
        size(imagingData.nanmask,3) < blockID

    error( ...
        'plotDemoOptostim:MissingROIMask', ...
        'imagingData.nanmask(:,:,blockID) is unavailable.');
end

roiReference = ...
    isfinite(imagingData.nanmask(:,:,blockID)) & ...
    imagingData.nanmask(:,:,blockID) ~= 0;

roiMask = demoWarpBinaryMaskToCurrentCamera( ...
    roiReference, ...
    bitmapData, ...
    blockID, ...
    currentCameraRef);

% =====================================================================
% 6. Orientation-specific Gaussian footprints
% =====================================================================

if ~isfield(demoProducts, 'gaussianMaskCamspace')
    error( ...
        'plotDemoOptostim:MissingGaussianMasks', ...
        'demoProducts.gaussianMaskCamspace is unavailable.');
end

gaussMask0 = ...
    demoProducts.gaussianMaskCamspace(:,:,demoIdx0) > 0.5;

gaussMask90 = ...
    demoProducts.gaussianMaskCamspace(:,:,demoIdx90) > 0.5;

if ~isequal(size(gaussMask0), size(columnMap0Current)) || ...
        ~isequal(size(gaussMask90), size(columnMap0Current))

    error( ...
        'plotDemoOptostim:GaussianSizeMismatch', ...
        ['Session %d: Gaussian masks do not match the ' ...
         'current-camera column-map dimensions.'], ...
        currentSessID);
end

% Plot only the larger of the two orientation-specific Gaussian footprints.
% Both original masks remain available for constructing their corresponding
% designed targets and for numerical output.
if nnz(gaussMask0) >= nnz(gaussMask90)

    gaussMaskLargest = gaussMask0;
    largestGaussianOrientation = 0;

else

    gaussMaskLargest = gaussMask90;
    largestGaussianOrientation = 90;
end

% =====================================================================
% 7. Designed pre-projector target columns
% =====================================================================

targetDesigned0 = demoBuildDesignedTarget( ...
    columnMap0Current, ...
    gaussMask0, ...
    bitmapData, ...
    coregIdx0, ...
    blockID);

targetDesigned90 = demoBuildDesignedTarget( ...
    columnMap90Current, ...
    gaussMask90, ...
    bitmapData, ...
    coregIdx90, ...
    blockID);

% The designed targets should be contained by their matching masks.

outsideGaussian0 = targetDesigned0 & ~gaussMask0;
outsideGaussian90 = targetDesigned90 & ~gaussMask90;

if any(outsideGaussian0(:))
    error( ...
        'plotDemoOptostim:TargetOutsideGaussian0', ...
        ['Session %d: %d designed 0-degree target pixels lie ' ...
         'outside the 0-degree Gaussian footprint.'], ...
        currentSessID, ...
        sum(outsideGaussian0(:)));
end

if any(outsideGaussian90(:))
    error( ...
        'plotDemoOptostim:TargetOutsideGaussian90', ...
        ['Session %d: %d designed 90-degree target pixels lie ' ...
         'outside the 90-degree Gaussian footprint.'], ...
        currentSessID, ...
        sum(outsideGaussian90(:)));
end

% =====================================================================
% 8. Recovered projector targets retained only for QC
% =====================================================================

if isfield(demoProducts, 'targetedColumnsCamspace')

    targetRecovered0Raw = double( ...
        demoProducts.targetedColumnsCamspace(:,:,demoIdx0));

    targetRecovered90Raw = double( ...
        demoProducts.targetedColumnsCamspace(:,:,demoIdx90));

    targetRecovered0 = ...
        isfinite(targetRecovered0Raw) & targetRecovered0Raw >= 0.5;

    targetRecovered90 = ...
        isfinite(targetRecovered90Raw) & targetRecovered90Raw >= 0.5;

else

    targetRecovered0 = false(size(targetDesigned0));
    targetRecovered90 = false(size(targetDesigned90));
end

% =====================================================================
% 9. Load actual 0%-contrast integrated opto-response difference
% =====================================================================

[zeroContrastOptoDifference, zeroContrastConditionInfo] = ...
    demoLoadZeroContrastOptoDifference( ...
        trialStructureFile, ...
        integratedResponseFile);

if ~isequal(size(zeroContrastOptoDifference), size(columnMap0Current))
    error( ...
        'plotDemoOptostim:IntegratedResponseSizeMismatch', ...
        ['Panel-B integrated response is [%d %d], but current-camera ' ...
         'products are [%d %d]. No automatic resizing was performed.'], ...
        size(zeroContrastOptoDifference,1), ...
        size(zeroContrastOptoDifference,2), ...
        size(columnMap0Current,1), ...
        size(columnMap0Current,2));
end

% =====================================================================
% 9b. Apply the stabilization offset and bandpass the measured response
% =====================================================================

bandpassSF = [0.8 3];  % cycles/mm

if ~isfield(zeroContrastConditionInfo, 'imagingSizePxl') || ...
        isempty(zeroContrastConditionInfo.imagingSizePxl) || ...
        ~isscalar(zeroContrastConditionInfo.imagingSizePxl) || ...
        ~isfinite(zeroContrastConditionInfo.imagingSizePxl) || ...
        zeroContrastConditionInfo.imagingSizePxl <= 0

    error( ...
        'plotDemoOptostim:MissingImagingSizePxl', ...
        'TS.Header.Imaging.SizePxl is missing or invalid.');
end

[meanStabilizationDx, meanStabilizationDy, stabilizationInfo] = ...
    demoLoadStabilizationOffsets(stabilizationFile);

% Register Panel B's measured activity to Panel A's PCA-denoised
% difference map. Panel A is the fixed image; Panel B is the moving image.
% The bitmap, ROI and Gaussian overlays remain fixed in current-camera
% coordinates.
activityTransformMode = 'rigid';
activityRegistrationSource = 'bandpass';

zeroContrastOptoDifferenceUnaligned = ...
    zeroContrastOptoDifference;

zeroContrastOptoDifferenceBandpassUnaligned = ...
    demoBandpassScalarMap( ...
        zeroContrastOptoDifferenceUnaligned, ...
        bandpassSF, ...
        zeroContrastConditionInfo.imagingSizePxl);

% Estimate the transform only from the valid imaging ROI. Erode the ROI
% slightly so the optimizer cannot lock onto the hard mask boundary. The
% displayed bitmap, ROI and Gaussian overlays remain completely fixed.
registrationMask = imerode( ...
    roiMask, ...
    strel('disk', 8, 0));

if nnz(registrationMask) < 500
    registrationMask = roiMask;
end

% The sign convention of refcfg.dx/dy is not explicit. Test full 2-D and
% horizontal-only stabilization seeds, then refine the measured activity
% with a constrained ROI-only rigid optimizer. Horizontal-only seeds are
% included because the
% visible mismatch appears mainly lateral while still being derived from
% the stabilization parameters rather than a manually imposed shift.
stabilizationCandidateLabels = { ...
    'no stabilization seed'; ...
    '+mean refcfg x/y seed'; ...
    '-mean refcfg x/y seed'; ...
    '+mean refcfg x-only seed'; ...
    '-mean refcfg x-only seed'};

stabilizationCandidateShiftsPx = [ ...
     0, 0; ...
     meanStabilizationDx, meanStabilizationDy; ...
    -meanStabilizationDx,-meanStabilizationDy; ...
     meanStabilizationDx, 0; ...
    -meanStabilizationDx, 0];

nStabilizationCandidates = ...
    size(stabilizationCandidateShiftsPx,1);

stabilizationRawCandidates = ...
    cell(nStabilizationCandidates,1);

stabilizationBandpassCandidates = ...
    cell(nStabilizationCandidates,1);

activityTransformCandidates = ...
    cell(nStabilizationCandidates,1);

activityTransformInfoCandidates = ...
    cell(nStabilizationCandidates,1);

stabilizationCandidateR = ...
    nan(nStabilizationCandidates,1);

stabilizationCandidateRSquared = ...
    nan(nStabilizationCandidates,1);

stabilizationCandidateNPixels = ...
    nan(nStabilizationCandidates,1);

candidateSelectionScores = ...
    -inf(nStabilizationCandidates,1);

for stabilizationCandidateIndex = 1:nStabilizationCandidates

    initialShift = ...
        stabilizationCandidateShiftsPx( ...
            stabilizationCandidateIndex,:);

    try
        [combinedTform, combinedInfo] = ...
            demoOptimizeRigidActivityTransform( ...
                pcaDifference, ...
                zeroContrastOptoDifferenceBandpassUnaligned, ...
                registrationMask, ...
                initialShift);

        combinedInfo.refinementSucceeded = true;

    catch registrationError

        warning( ...
            'plotDemoOptostim:RigidCandidateFallback', ...
            ['Rigid refinement failed for seed %s: %s. ' ...
             'Using the seed translation without rotation.'], ...
            stabilizationCandidateLabels{stabilizationCandidateIndex}, ...
            registrationError.message);

        combinedTform = affine2d([ ...
            1 0 0; ...
            0 1 0; ...
            initialShift(1) initialShift(2) 1]);

        combinedInfo = demoDecomposeAffine2D(combinedTform);
        combinedInfo.refinementSucceeded = false;
        combinedInfo.objectiveValue = NaN;
    end

    combinedInfo.initialShiftPx = initialShift;

    activityTransformCandidates{stabilizationCandidateIndex} = ...
        combinedTform;

    activityTransformInfoCandidates{stabilizationCandidateIndex} = ...
        combinedInfo;

    stabilizationRawCandidates{stabilizationCandidateIndex} = ...
        demoApplyGeometricTransform( ...
            zeroContrastOptoDifferenceUnaligned, ...
            combinedTform, ...
            size(pcaDifference), ...
            'linear');

    stabilizationBandpassCandidates{stabilizationCandidateIndex} = ...
        demoApplyGeometricTransform( ...
            zeroContrastOptoDifferenceBandpassUnaligned, ...
            combinedTform, ...
            size(pcaDifference), ...
            'linear');

    [stabilizationCandidateR(stabilizationCandidateIndex), ...
     stabilizationCandidateRSquared(stabilizationCandidateIndex), ...
     stabilizationCandidateNPixels(stabilizationCandidateIndex)] = ...
        demoPearsonRSquared( ...
            pcaDifference, ...
            stabilizationBandpassCandidates{ ...
                stabilizationCandidateIndex}, ...
            gaussMaskLargest);

    transformIsPlausible = ...
        all(isfinite(combinedInfo.translationPx)) && ...
        isfinite(combinedInfo.rotationDeg) && ...
        isfinite(combinedInfo.scaleX) && ...
        isfinite(combinedInfo.scaleY) && ...
        norm(combinedInfo.translationPx) <= 90 && ...
        abs(combinedInfo.rotationDeg) <= 20 && ...
        combinedInfo.scaleX >= 0.98 && ...
        combinedInfo.scaleX <= 1.02 && ...
        combinedInfo.scaleY >= 0.98 && ...
        combinedInfo.scaleY <= 1.02;

    if transformIsPlausible && ...
            isfinite(stabilizationCandidateRSquared( ...
                stabilizationCandidateIndex))

        candidateSelectionScores(stabilizationCandidateIndex) = ...
            stabilizationCandidateRSquared( ...
                stabilizationCandidateIndex);
    end
end

% Do not abort the whole pipeline if the refinement optimizer fails its
% plausibility checks. Fall back to the best finite candidate and warn.
if all(~isfinite(candidateSelectionScores)) || ...
        all(candidateSelectionScores == -Inf)

    finiteCandidateScores = stabilizationCandidateRSquared;
    finiteCandidateScores(~isfinite(finiteCandidateScores)) = -Inf;

    if all(finiteCandidateScores == -Inf)
        error( ...
            'plotDemoOptostim:ActivityRegistrationFailed', ...
            'Rigid activity registration produced no finite candidates.');
    end

    warning( ...
        'plotDemoOptostim:UsingBestUnconstrainedTransform', ...
        ['No candidate passed all rigid-transform plausibility limits. ' ...
         'Using the finite candidate with the highest Gaussian-region R^2.']);

    candidateSelectionScores = finiteCandidateScores;
end

[~, selectedStabilizationCandidate] = ...
    max(candidateSelectionScores);

activityTform = ...
    activityTransformCandidates{selectedStabilizationCandidate};

activityTransformInfo = ...
    activityTransformInfoCandidates{selectedStabilizationCandidate};

selectedStabilizationShiftPx = ...
    activityTransformInfo.translationPx;

selectedStabilizationLabel = sprintf( ...
    '%s + %s activity transform', ...
    stabilizationCandidateLabels{selectedStabilizationCandidate}, ...
    activityTransformMode);

zeroContrastOptoDifference = ...
    stabilizationRawCandidates{selectedStabilizationCandidate};

zeroContrastOptoDifferenceBandpass = ...
    stabilizationBandpassCandidates{selectedStabilizationCandidate};

% Apply the selected activity transform separately to the two underlying
% measured component maps. These remain unfiltered.
measuredActivity0CoregRaw = demoApplyGeometricTransform( ...
    zeroContrastConditionInfo.response0, ...
    activityTform, ...
    size(pcaDifference), ...
    'linear');

measuredActivity90CoregRaw = demoApplyGeometricTransform( ...
    zeroContrastConditionInfo.response90, ...
    activityTform, ...
    size(pcaDifference), ...
    'linear');

measuredActivityDifferenceCoregRaw = ...
    measuredActivity90CoregRaw - measuredActivity0CoregRaw;

pearsonR = ...
    stabilizationCandidateR(selectedStabilizationCandidate);

pearsonRSquared = ...
    stabilizationCandidateRSquared(selectedStabilizationCandidate);

nCorrelationPixels = ...
    stabilizationCandidateNPixels(selectedStabilizationCandidate);

if ~isequal(size(zeroContrastOptoDifferenceBandpass), ...
        size(zeroContrastOptoDifference))

    error( ...
        'plotDemoOptostim:BandpassSizeMismatch', ...
        ['Bandpassed response is [%d %d], while the aligned raw response ' ...
         'is [%d %d].'], ...
        size(zeroContrastOptoDifferenceBandpass,1), ...
        size(zeroContrastOptoDifferenceBandpass,2), ...
        size(zeroContrastOptoDifference,1), ...
        size(zeroContrastOptoDifference,2));
end

% =====================================================================
% 10. Validate masks and dimensions
% =====================================================================

demoValidateDimensions( ...
    pcaDifference, ...
    roiMask, ...
    gaussMask0, ...
    gaussMask90, ...
    targetDesigned0, ...
    targetDesigned90, ...
    zeroContrastOptoDifference);

if ~any(roiMask(:))
    error( ...
        'plotDemoOptostim:EmptyROI', ...
        'Session %d: coregistered ROI mask is empty.', ...
        currentSessID);
end

if ~any(gaussMask0(:))
    warning( ...
        'plotDemoOptostim:EmptyGaussian0', ...
        'Session %d: 0-degree Gaussian footprint is empty.', ...
        currentSessID);
end

if ~any(gaussMask90(:))
    warning( ...
        'plotDemoOptostim:EmptyGaussian90', ...
        'Session %d: 90-degree Gaussian footprint is empty.', ...
        currentSessID);
end

if ~any(targetDesigned0(:))
    error( ...
        'plotDemoOptostim:EmptyDesignedTarget0', ...
        'Session %d: designed 0-degree target is empty.', ...
        currentSessID);
end

if ~any(targetDesigned90(:))
    error( ...
        'plotDemoOptostim:EmptyDesignedTarget90', ...
        'Session %d: designed 90-degree target is empty.', ...
        currentSessID);
end

% =====================================================================
% 11. Physical coordinates
% =====================================================================

[xMM, yMM, pixelSizeMM] = demoComputeMMCoordinates( ...
    imagingData, ...
    blockID, ...
    pcaDifference);

% =====================================================================
% 12. Symmetric color limits
% =====================================================================

pcaColorLimits = demoSymmetricColorLimits( ...
    pcaDifference, ...
    validPcaMask & isfinite(pcaDifference), ...
    'PCA difference', ...
    currentSessID);

zeroContrastValidMask = isfinite(zeroContrastOptoDifference);

zeroContrastColorLimits = demoSymmetricColorLimits( ...
    zeroContrastOptoDifference, ...
    zeroContrastValidMask, ...
    '0%-contrast integrated response difference', ...
    currentSessID);

bandpassValidMask = ...
    isfinite(zeroContrastOptoDifferenceBandpass);

bandpassColorLimits = demoSymmetricColorLimits( ...
    zeroContrastOptoDifferenceBandpass, ...
    bandpassValidMask, ...
    '0%-contrast bandpassed response difference', ...
    currentSessID);

% Display-only copy: geometric warping leaves unsupported pixels as NaN,
% which appear as a light-gray strip. Zero is the midpoint of the shared
% symmetric c-axis, so use zero-valued padding for a neutral mean-gray edge.
zeroContrastOptoDifferenceBandpassDisplay = ...
    zeroContrastOptoDifferenceBandpass;

zeroContrastOptoDifferenceBandpassDisplay( ...
    ~isfinite(zeroContrastOptoDifferenceBandpassDisplay)) = 0;
% =====================================================================
% 13. Target overlap and projector QC
% =====================================================================

targetOverlap = ...
    targetDesigned0 & targetDesigned90;

nTargetOverlap = sum(targetOverlap(:));

if nTargetOverlap > 0
    warning( ...
        'plotDemoOptostim:DesignedTargetOverlap', ...
        ['Session %d: %d pixels overlap between designed ' ...
         '0-degree and 90-degree targets.'], ...
        currentSessID, ...
        nTargetOverlap);
end

diceRecovered0 = demoDiceCoefficient( ...
    targetDesigned0, ...
    targetRecovered0);

diceRecovered90 = demoDiceCoefficient( ...
    targetDesigned90, ...
    targetRecovered90);


% Use exactly the same designed current-camera target masks in Panels A
% and B. Do not substitute the projector-recovered masks here: that change
% produced a visibly worse overlay and mixes a different reconstruction
% pathway into the panel-to-panel comparison.
panelBTarget0 = targetDesigned0;
panelBTarget90 = targetDesigned90;
panelBTargetSource = 'same designed current-camera targets as Panel A';

panelBTargetOverlap = targetOverlap;
nPanelBTargetOverlap = nTargetOverlap;

% Mean stimulation metadata across the 0-degree and 90-degree patterns.
stimulationSummary = struct();

stimulationSummary.meanColumns = ...
    demoMeanBitmapMetric(bitmapData, 'nColumns', blockID);

stimulationSummary.meanPixelsON = ...
    demoMeanBitmapMetric(bitmapData, 'pixelsON', blockID);

stimulationSummary.meanTotalPower_mW = ...
    demoMeanBitmapMetric( ...
        bitmapData, ...
        'totalPowerToOnPixelsWithinROI_mW', ...
        blockID);

stimulationSummary.meanPowerDensityWithinROI_mWmm2 = ...
    demoMeanBitmapMetric( ...
        bitmapData, ...
        'meanPowerDensityWithinROI_mWmm2', ...
        blockID);

stimulationSummary.pearsonRSquared = pearsonRSquared;

% Fallbacks are used only if older bitmapData files lack the count fields.
if ~isfinite(stimulationSummary.meanColumns)
    connectedColumns0 = bwconncomp(targetDesigned0);
    connectedColumns90 = bwconncomp(targetDesigned90);
    stimulationSummary.meanColumns = mean([ ...
        connectedColumns0.NumObjects, ...
        connectedColumns90.NumObjects]);
end

if ~isfinite(stimulationSummary.meanPixelsON)
    stimulationSummary.meanPixelsON = mean([ ...
        nnz(targetDesigned0), ...
        nnz(targetDesigned90)]);
end

% =====================================================================
% 14. Diagnostics
% =====================================================================

fprintf('\n');
fprintf('--- Demo optostim diagnostics ---\n');
fprintf('Session:                         %d\n', currentSessID);
fprintf('Coordinate frame:                current-session camera\n');
fprintf('Registration direction:         Panel B activity -> Panel A PCA map\n');
fprintf('PCA orientations:                [%s]\n', num2str(pcaOrts));
fprintf('Bitmap orientations:             [%s]\n', num2str(coregOrts));
fprintf('Image dimensions:                %d x %d\n', ...
    size(pcaDifference,1), size(pcaDifference,2));
fprintf('Pixel size:                      %.6f mm/px\n', ...
    pixelSizeMM);
fprintf('ROI pixels:                      %d\n', ...
    sum(roiMask(:)));
fprintf('Finite PCA pixels outside ROI:   %d\n', ...
    nnz(isfinite(pcaDifference) & ~roiMask));
fprintf('0-deg Gaussian pixels:           %d\n', ...
    sum(gaussMask0(:)));
fprintf('90-deg Gaussian pixels:          %d\n', ...
    sum(gaussMask90(:)));
fprintf('Displayed Gaussian footprint:    %d deg (%d pixels)\n', ...
    largestGaussianOrientation, sum(gaussMaskLargest(:)));
fprintf('0-deg designed target pixels:    %d\n', ...
    sum(targetDesigned0(:)));
fprintf('90-deg designed target pixels:   %d\n', ...
    sum(targetDesigned90(:)));
fprintf('Designed target overlap:         %d\n', ...
    nTargetOverlap);
fprintf('0-deg recovered/design Dice:     %.4f\n', ...
    diceRecovered0);
fprintf('90-deg recovered/design Dice:    %.4f\n', ...
    diceRecovered90);
fprintf('PCA difference range:            [%.5g, %.5g]\n', ...
    min(pcaDifference(validPcaMask & isfinite(pcaDifference))), ...
    max(pcaDifference(validPcaMask & isfinite(pcaDifference))));
fprintf('Panel-B O00000 condition(s):     [%s]\n', ...
    num2str(zeroContrastConditionInfo.conditionIndices0));
fprintf('Panel-B O09000 condition(s):     [%s]\n', ...
    num2str(zeroContrastConditionInfo.conditionIndices90));
fprintf('Panel-B target overlay source:   %s\n', ...
    panelBTargetSource);
fprintf('Stabilization file:              %s\n', ...
    stabilizationFile);
fprintf('Stabilizer pixel size:           %.8f mm/px\n', ...
    stabilizationInfo.sizePxlMM);
fprintf('Mean refcfg dx, dy (native):     [%.4f, %.4f] mm\n', ...
    stabilizationInfo.meanDxNative, ...
    stabilizationInfo.meanDyNative);
fprintf('Mean refcfg dx, dy (converted):  [%.4f, %.4f] px\n', ...
