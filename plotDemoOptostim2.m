function shiftedMap = demoTranslateScalarMap(imageData, dxPixels, dyPixels)

    imageData = double(imageData);
    validMask = isfinite(imageData);

    filledImage = imageData;
    filledImage(~validMask) = 0;

    outputRef = imref2d(size(imageData));

    translationTransform = affine2d([ ...
        1, 0, 0; ...
        0, 1, 0; ...
        dxPixels, dyPixels, 1]);

    shiftedMap = imwarp( ...
        filledImage, ...
        translationTransform, ...
        'linear', ...
        'OutputView', outputRef, ...
        'FillValues', 0);

    shiftedValidity = imwarp( ...
        double(validMask), ...
        translationTransform, ...
        'linear', ...
        'OutputView', outputRef, ...
        'FillValues', 0);

    shiftedMap(shiftedValidity < 0.999) = NaN;
end


