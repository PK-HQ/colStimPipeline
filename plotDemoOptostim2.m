% =====================================================================
% Mean one bitmap metric across the two orientation patterns
% =====================================================================

function meanValue = ...
        demoMeanBitmapMetric(bitmapData, fieldName, blockID)

    meanValue = NaN;

    if ~isfield(bitmapData, fieldName) || ...
            isempty(bitmapData.(fieldName))
        return;
    end

    fieldData = double(bitmapData.(fieldName));

    orientationByBlockFields = { ...
        'nColumns', ...
        'pixelsON'};

    orientationInSecondDimensionFields = { ...
        'totalPowerToOnPixelsWithinROI_mW', ...
        'meanPowerDensityWithinROI_mWmm2', ...
        'projectorPowerDensity_mWmm2', ...
        'temporalDutyCycle'};

    if any(strcmp(fieldName, orientationByBlockFields))

        if size(fieldData,2) < blockID
            return;
        end

        blockValues = fieldData(:,blockID);

    elseif any(strcmp(fieldName, ...
            orientationInSecondDimensionFields))

        if ndims(fieldData) >= 3

            if size(fieldData,3) < blockID
                return;
            end

            blockValues = fieldData(:,:,blockID);

        elseif blockID == 1

            % MATLAB suppresses a trailing singleton third dimension, so
            % [1 x 2 x 1] may appear as [1 x 2]. In that case both values
            % still belong to block 1 and must both be averaged.
            blockValues = fieldData;

        else

            return;
        end

    else

        % Conservative generic fallback for any later metric.
        if ndims(fieldData) >= 3

            if size(fieldData, ndims(fieldData)) < blockID
                return;
            end

            indices = repmat({':'}, 1, ndims(fieldData));
            indices{end} = blockID;
            blockValues = fieldData(indices{:});

        elseif size(fieldData,2) >= blockID

            blockValues = fieldData(:,blockID);

        elseif size(fieldData,1) >= blockID

            blockValues = fieldData(blockID,:);

        else

            return;
        end
    end

    blockValues = blockValues(isfinite(blockValues));

    if isempty(blockValues)
        return;
    end

    meanValue = mean(blockValues(:));
end


% =====================================================================
% Pearson r and r-squared within a binary comparison mask
% =====================================================================

function [pearsonR, pearsonRSquared, nPixels] = ...
        demoPearsonRSquared(mapA, mapB, comparisonMask)

    validMask = ...
        logical(comparisonMask) & ...
        isfinite(mapA) & ...
        isfinite(mapB);

    valuesA = double(mapA(validMask));
    valuesB = double(mapB(validMask));

    nPixels = numel(valuesA);

    if nPixels < 3 || std(valuesA) == 0 || std(valuesB) == 0

        pearsonR = NaN;
        pearsonRSquared = NaN;
        return;
    end

    correlationMatrix = corrcoef(valuesA, valuesB);
    pearsonR = correlationMatrix(1,2);
    pearsonRSquared = pearsonR.^2;
end


% =====================================================================
% Normalize TS.Header.Conditions.ProjImg into a cell array of char
% =====================================================================

function imageList = demoNormalizeProjImgList(projectorImages, nConditions)

    imageList = cell(nConditions,1);

    if iscell(projectorImages)

        if numel(projectorImages) ~= nConditions
            error( ...
                'plotDemoOptostim:ProjImgLengthMismatch', ...
                'ProjImg contains %d entries; expected %d.', ...
                numel(projectorImages), ...
                nConditions);
        end

        for conditionIndex = 1:nConditions
            imageList{conditionIndex} = ...
                demoConvertProjImgEntry(projectorImages{conditionIndex});
        end

        return;
    end

    if isstring(projectorImages)

        if numel(projectorImages) ~= nConditions
            error( ...
                'plotDemoOptostim:ProjImgLengthMismatch', ...
                'ProjImg contains %d entries; expected %d.', ...
                numel(projectorImages), ...
                nConditions);
        end

        for conditionIndex = 1:nConditions
            imageList{conditionIndex} = ...
                char(projectorImages(conditionIndex));
        end

        return;
    end

    if ischar(projectorImages)

        if nConditions == 1

            imageList{1} = strtrim(projectorImages);
            return;
        end

        if size(projectorImages,1) == nConditions

            for conditionIndex = 1:nConditions
                imageList{conditionIndex} = ...
                    strtrim(projectorImages(conditionIndex,:));
            end

            return;
        end
    end

    error( ...
        'plotDemoOptostim:UnsupportedProjImgType', ...
        'Unsupported TS.Header.Conditions.ProjImg representation.');
end


