% =====================================================================
% Reconstruct a designed pre-projector target
% =====================================================================

function targetMask = demoBuildDesignedTarget( ...
        coregisteredColumnMap, ...
        gaussianMask, ...
        bitmapData, ...
        bitmapIndex, ...
        blockID)

    targetMask = ...
        coregisteredColumnMap > 0.5 & ...
        gaussianMask;

    if isfield(bitmapData, 'nColumnsWanted') && ...
            size(bitmapData.nColumnsWanted,2) >= bitmapIndex && ...
            size(bitmapData.nColumnsWanted,3) >= blockID

        nColumnsWanted = ...
            bitmapData.nColumnsWanted(1,bitmapIndex,blockID);

        contourLevel = NaN;

        if isfield(bitmapData, 'gaussianContourLevel') && ...
                size(bitmapData.gaussianContourLevel,2) >= bitmapIndex && ...
                size(bitmapData.gaussianContourLevel,3) >= blockID

            contourLevel = ...
                bitmapData.gaussianContourLevel(1,bitmapIndex,blockID);
        end

        if isfinite(nColumnsWanted) && ...
                nColumnsWanted == 1 && ...
                isfinite(contourLevel) && ...
                contourLevel < 200

            targetMask = bwareaopen(targetMask, 300);
        end
    end
end


% =====================================================================
% Load Panel-B integrated response
% =====================================================================

function [differenceMap, conditionInfo] = ...
        demoLoadZeroContrastOptoDifference( ...
            trialStructureFile, ...
            integratedResponseFile)
    
    if exist(trialStructureFile, 'file') ~= 2
        error( ...
            'plotDemoOptostim:MissingTSFile', ...
            'Could not find TS file: %s', ...
            trialStructureFile);
    end

    if exist(integratedResponseFile, 'file') ~= 2
        error( ...
            'plotDemoOptostim:MissingIntegratedResponseFile', ...
            'Could not find integrated-response file: %s', ...
            integratedResponseFile);
    end

    tsLoaded = load(trialStructureFile, 'TS');
    responseLoaded = load(integratedResponseFile, 'DataCond');

    if ~isfield(tsLoaded, 'TS')
        error( ...
            'plotDemoOptostim:MissingTSVariable', ...
            'The file %s does not contain TS.', ...
            trialStructureFile);
    end

    if ~isfield(responseLoaded, 'DataCond')
        error( ...
            'plotDemoOptostim:MissingDataCond', ...
            'The file %s does not contain DataCond.', ...
            integratedResponseFile);
    end

    TS = tsLoaded.TS;
    DataCond = responseLoaded.DataCond;

    if ~isfield(TS.Header, 'Imaging') || ...
            ~isfield(TS.Header.Imaging, 'SizePxl') || ...
            isempty(TS.Header.Imaging.SizePxl)
    
        error( ...
            'plotDemoOptostim:MissingImagingSizePxl', ...
            'TS.Header.Imaging.SizePxl is unavailable.');
    end
    
    imagingSizePxl = double(TS.Header.Imaging.SizePxl);
    
    if ~isscalar(imagingSizePxl) || ...
            ~isfinite(imagingSizePxl) || ...
            imagingSizePxl <= 0
    
        error( ...
            'plotDemoOptostim:InvalidImagingSizePxl', ...
            'TS.Header.Imaging.SizePxl must be a positive scalar.');
    end

    if ~isfield(TS, 'Header') || ...
            ~isfield(TS.Header, 'Conditions')

        error( ...
            'plotDemoOptostim:MissingConditions', ...
            'TS.Header.Conditions is unavailable.');
    end

    conditions = TS.Header.Conditions;

    requiredFields = { ...
        'StimCon', ...
        'ProjImg'};

    for fieldIndex = 1:numel(requiredFields)

        if ~isfield(conditions, requiredFields{fieldIndex})

            error( ...
                'plotDemoOptostim:MissingConditionField', ...
                'TS.Header.Conditions.%s is unavailable.', ...
                requiredFields{fieldIndex});
        end
    end

    stimContrast = double(conditions.StimCon(:));

    nConditions = numel(stimContrast);

    if size(DataCond,3) ~= nConditions

        error( ...
            'plotDemoOptostim:DataCondConditionMismatch', ...
            ['DataCond contains %d condition slices, while TS defines ' ...
             '%d conditions.'], ...
            size(DataCond,3), ...
            nConditions);
    end

    projectorImages = demoNormalizeProjImgList( ...
        conditions.ProjImg, ...
        nConditions);

    isZeroDegreeBitmap = false(nConditions,1);
    isNinetyDegreeBitmap = false(nConditions,1);

    for conditionIndex = 1:nConditions

        imageBaseName = demoImageBaseName( ...
            projectorImages{conditionIndex});

        isZeroDegreeBitmap(conditionIndex) = ...
            strncmpi(imageBaseName, 'O00000', 6);

        isNinetyDegreeBitmap(conditionIndex) = ...
            strncmpi(imageBaseName, 'O09000', 6);
    end

    isOptoCondition = true(nConditions,1);

    if isfield(conditions, 'TypeCond')

        typeCondition = double(conditions.TypeCond(:));

        if numel(typeCondition) == nConditions
            isOptoCondition = typeCondition == 3;
        end
    end

    commonSelection = ...
        stimContrast == 0 & ...
        isOptoCondition;

    conditionIndices0 = find( ...
        commonSelection & ...
        isZeroDegreeBitmap);

    conditionIndices90 = find( ...
        commonSelection & ...
        isNinetyDegreeBitmap);

    if isempty(conditionIndices0)

        error( ...
            'plotDemoOptostim:MissingZeroContrastO00000', ...
            'No 0%%-contrast O00000 optostimulation condition was found.');
    end

    if isempty(conditionIndices90)

        error( ...
            'plotDemoOptostim:MissingZeroContrastO09000', ...
            'No 0%%-contrast O09000 optostimulation condition was found.');
    end

    response0 = demoMeanConditionMaps( ...
        DataCond, ...
        conditionIndices0);

    response90 = demoMeanConditionMaps( ...
        DataCond, ...
        conditionIndices90);

    differenceMap = response90 - response0;

    conditionInfo = struct();
    conditionInfo.conditionIndices0 = ...
        conditionIndices0(:)';

    conditionInfo.conditionIndices90 = ...
        conditionIndices90(:)';

    conditionInfo.projectorImages0 = ...
        projectorImages(conditionIndices0);

    conditionInfo.projectorImages90 = ...
        projectorImages(conditionIndices90);

    conditionInfo.response0 = response0;
    conditionInfo.response90 = response90;

    conditionInfo.imagingSizePxl = imagingSizePxl;
end


% =====================================================================
% Load mean stabilization offsets from a StabCfg file
% =====================================================================

function [meanDxPx, meanDyPx, stabilizationInfo] = ...
        demoLoadStabilizationOffsets(stabilizationFile)

    if exist(stabilizationFile, 'file') ~= 2
        error( ...
            'plotDemoOptostim:MissingStabilizationFile', ...
            'Could not find stabilization file: %s', ...
            stabilizationFile);
    end

    % This StabCfg contains both:
    %   refcfg.dx/refcfg.dy : reference-level translations
    %   ipu.SizePxl        : physical pixel size in mm/pixel
    %
    % The saved dx/dy values are in the same physical units as SizePxl,
    % not display pixels. Convert them to pixels before calling imwarp.
    loadedStabilization = load( ...
        stabilizationFile, ...
        'refcfg', ...
        'ipu');

    if ~isfield(loadedStabilization, 'refcfg') || ...
            ~isfield(loadedStabilization.refcfg, 'dx') || ...
            ~isfield(loadedStabilization.refcfg, 'dy')

        error( ...
            'plotDemoOptostim:MissingStabilizationOffsets', ...
            ['The stabilization file does not contain ' ...
             'refcfg.dx and refcfg.dy.']);
    end

    if ~isfield(loadedStabilization, 'ipu') || ...
            ~isfield(loadedStabilization.ipu, 'SizePxl') || ...
            isempty(loadedStabilization.ipu.SizePxl)

        error( ...
            'plotDemoOptostim:MissingStabilizationPixelSize', ...
            ['The stabilization file does not contain ' ...
             'ipu.SizePxl for conversion to pixels.']);
    end

    sizePxlMM = double(loadedStabilization.ipu.SizePxl);

    if ~isscalar(sizePxlMM) || ...
            ~isfinite(sizePxlMM) || ...
            sizePxlMM <= 0

        error( ...
            'plotDemoOptostim:InvalidStabilizationPixelSize', ...
            'ipu.SizePxl must be a positive finite scalar.');
    end

    dxValuesNative = ...
        double(loadedStabilization.refcfg.dx(:));

    dyValuesNative = ...
        double(loadedStabilization.refcfg.dy(:));

    finiteDxNative = ...
        dxValuesNative(isfinite(dxValuesNative));

    finiteDyNative = ...
        dyValuesNative(isfinite(dyValuesNative));

    if isempty(finiteDxNative) || isempty(finiteDyNative)
        error( ...
            'plotDemoOptostim:EmptyStabilizationOffsets', ...
            'refcfg.dx or refcfg.dy contains no finite values.');
    end

    meanDxNative = mean(finiteDxNative);
    meanDyNative = mean(finiteDyNative);

    meanDxPx = meanDxNative / sizePxlMM;
    meanDyPx = meanDyNative / sizePxlMM;

    stabilizationInfo = struct();
    stabilizationInfo.file = stabilizationFile;
    stabilizationInfo.sizePxlMM = sizePxlMM;
    stabilizationInfo.nativeUnits = 'mm';
    stabilizationInfo.nDx = numel(finiteDxNative);
    stabilizationInfo.nDy = numel(finiteDyNative);

    stabilizationInfo.meanDxNative = meanDxNative;
    stabilizationInfo.meanDyNative = meanDyNative;
    stabilizationInfo.medianDxNative = median(finiteDxNative);
    stabilizationInfo.medianDyNative = median(finiteDyNative);
    stabilizationInfo.minDxNative = min(finiteDxNative);
    stabilizationInfo.maxDxNative = max(finiteDxNative);
    stabilizationInfo.minDyNative = min(finiteDyNative);
    stabilizationInfo.maxDyNative = max(finiteDyNative);

    stabilizationInfo.meanDxPx = meanDxPx;
    stabilizationInfo.meanDyPx = meanDyPx;
    stabilizationInfo.medianDxPx = ...
        stabilizationInfo.medianDxNative / sizePxlMM;
    stabilizationInfo.medianDyPx = ...
        stabilizationInfo.medianDyNative / sizePxlMM;
    stabilizationInfo.minDxPx = ...
        stabilizationInfo.minDxNative / sizePxlMM;
    stabilizationInfo.maxDxPx = ...
        stabilizationInfo.maxDxNative / sizePxlMM;
    stabilizationInfo.minDyPx = ...
        stabilizationInfo.minDyNative / sizePxlMM;
    stabilizationInfo.maxDyPx = ...
        stabilizationInfo.maxDyNative / sizePxlMM;
end

% =====================================================================
% Translate a scalar map while preserving its finite-data support
