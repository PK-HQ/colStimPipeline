% =====================================================================
% Warp PCA into current-session camera space
% =====================================================================

function [pca0Current, pca90Current, validMask] = ...
        demoWarpPcaToCurrentCamera( ...
            pca0Reference, ...
            pca90Reference, ...
            bitmapData, ...
            blockID, ...
            outputRef)

    transformReferenceToCurrent = ...
        demoGetReferenceToCurrentTransform(bitmapData, blockID);

    valid0Reference = isfinite(pca0Reference);
    valid90Reference = isfinite(pca90Reference);

    pca0Filled = pca0Reference;
    pca90Filled = pca90Reference;

    pca0Filled(~valid0Reference) = 0;
    pca90Filled(~valid90Reference) = 0;

    pca0Current = imwarp( ...
        pca0Filled, ...
        transformReferenceToCurrent, ...
        'linear', ...
        'OutputView', outputRef, ...
        'FillValues', 0);

    pca90Current = imwarp( ...
        pca90Filled, ...
        transformReferenceToCurrent, ...
        'linear', ...
        'OutputView', outputRef, ...
        'FillValues', 0);

    valid0Current = imwarp( ...
        double(valid0Reference), ...
        transformReferenceToCurrent, ...
        'linear', ...
        'OutputView', outputRef, ...
        'FillValues', 0);

    valid90Current = imwarp( ...
        double(valid90Reference), ...
        transformReferenceToCurrent, ...
        'linear', ...
        'OutputView', outputRef, ...
        'FillValues', 0);

    validMask = ...
        valid0Current > 0.999 & ...
        valid90Current > 0.999;

    % Do not mask the PCA maps with the finite-support/ROI mask. The mask is
    % returned only for diagnostics and color-limit estimation.
end


