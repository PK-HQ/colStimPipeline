        set(axesHandles(axisIndex), 'Position', newPosition);
    end
end


% =====================================================================
% Dice coefficient for projector QC
% =====================================================================

function diceValue = demoDiceCoefficient(maskA, maskB)

    denominator = sum(maskA(:)) + sum(maskB(:));

    if denominator == 0

        diceValue = NaN;
        return;
    end

    diceValue = ...
        2 * sum(maskA(:) & maskB(:)) / denominator;
end


