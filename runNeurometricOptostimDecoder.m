function decoderResult = runNeurometricOptostimDecoder( ...
    neurometricInput, saveFlag, plotFlag, userOptions)
%RUNNEUROMETRICOPTOSTIMDECODER Condition-average orientation decoder.
%
% This decoder is deliberately separate from
% runNeurometricOptostimAnalysis. It consumes the completed neurometric
% result structure or its saved MAT file and can therefore be revised and
% rerun without repeating image loading, coregistration, spatial filtering,
% or broad/DC fitting.
%
% INPUTS
%   neurometricInput
%       Either:
%         1) the neurometricOptostim result structure, or
%         2) a MAT-file containing neurometricOptostim.
%
%   saveFlag
%       1 saves the decoder result MAT file, PNG/FIG copies of every
%       plotted figure, and one multipage PDF with one figure per page.
%
%   plotFlag
%       1 leaves the figures visible. Figures are still generated invisibly
%       when saveFlag=1 and plotFlag=0.
%
%   userOptions
%       Optional structure overriding fields from
%       defaultNeurometricDecoderOptions.
%
% OUTPUT
%   decoderResult
%       Condition-average signed-pattern evidence, orientation bias,
%       similarity, separate column-domain activation, strength, and
%       coactivation metrics.
%
% SIGN CONVENTION
%   pattern.evidenceBias < 0  -> more 0-degree-like
%   pattern.evidenceBias > 0  -> more 90-degree-like
%
% IMPORTANT
%   This is a condition-average decoder/representation analysis. It is not
%   trial-wise classification accuracy and is not a formal confusion
%   matrix. Trial-wise decoding and cross-validation can be added later.

if nargin < 4 || isempty(userOptions)
    userOptions = struct();
end
if nargin < 3 || isempty(plotFlag)
    plotFlag = 1;
end
if nargin < 2 || isempty(saveFlag)
    saveFlag = 0;
end

[neurometricOptostim, inputAudit] = ...
    loadNeurometricDecoderInput(neurometricInput);

options = defaultNeurometricDecoderOptions(neurometricOptostim);
options = mergeStructFields(options, userOptions);
options.saveFlag = logical(saveFlag);
options.plotFlag = logical(plotFlag);

validateNeurometricDecoderInput(neurometricOptostim);

columnarMaps = double( ...
    neurometricOptostim.filteredMaps.columnar);

analysisMask = logical( ...
    neurometricOptostim.analysisMask);

templates = neurometricOptostim.templates;

decoderResult = calculateConditionAverageDecoder( ...
    columnarMaps, ...
    templates, ...
    analysisMask, ...
    neurometricOptostim.stimContrastMatrix, ...
    options);

decoderResult.metadata = struct();
decoderResult.metadata.analysisMode = ...
    'neurometric-optostim-decoder';
decoderResult.metadata.created = datestr(now, 30);
decoderResult.metadata.sessionLabel = options.sessionLabel;
decoderResult.metadata.inputAudit = inputAudit;
decoderResult.metadata.conditionDefinitions = ...
    neurometricOptostim.conditionDefinitions;
decoderResult.metadata.stimContrastMatrix = ...
    neurometricOptostim.stimContrastMatrix;
decoderResult.metadata.options = options;
decoderResult.metadata.codeVersion = options.codeVersion;

printNeurometricDecoderAudit(decoderResult);

outputFiles = struct();
decoderMatFile = '';

% Save numerical results before optional plotting.
if saveFlag
    if exist(options.outputDir, 'dir') ~= 7
        mkdir(options.outputDir);
    end

    decoderMatFile = fullfile( ...
        options.outputDir, ...
        sprintf('%s_neurometricOptostimDecoder.mat', ...
        options.sessionLabel));

    outputFiles.matFile = decoderMatFile;
    decoderResult.outputFiles = outputFiles;

    save(decoderMatFile, ...
        'decoderResult', ...
        '-v7.3');
end

if plotFlag || saveFlag
    originalVisibility = get(groot, 'DefaultFigureVisible');

    if ~plotFlag
        set(groot, 'DefaultFigureVisible', 'off');
    end

    try
        plotFiles = plotNeurometricDecoderQC( ...
            decoderResult, ...
            neurometricOptostim, ...
            options);

        outputFiles = mergeStructFields( ...
            outputFiles, plotFiles);

        decoderResult.outputFiles = outputFiles;

        if saveFlag
            save(decoderMatFile, ...
                'decoderResult', ...
                '-v7.3');
        end
    catch ME
        set(groot, ...
            'DefaultFigureVisible', ...
            originalVisibility);

        decoderResult.plotError = ...
            getReport(ME, ...
            'extended', ...
            'hyperlinks', 'off');

        if saveFlag
            save(decoderMatFile, ...
                'decoderResult', ...
                '-v7.3');
        end

        rethrow(ME);
    end

    set(groot, ...
        'DefaultFigureVisible', ...
        originalVisibility);
end

end


function options = defaultNeurometricDecoderOptions( ...
    neurometricOptostim)

options = struct();

% Normalized scores are hidden when the corresponding raw strength falls
% below this fraction of the largest condition-average strength.
options.patternStrengthFloorFraction = 0.05;
options.domainStrengthFloorFraction = 0.05;

% Warn when the two signed PCA templates are nearly redundant or nearly
% exact opposites. Bias can still work, but coactivation cannot be inferred
% cleanly from signed-pattern projections alone.
options.templateCorrelationWarning = 0.80;

options.figurePositionPattern = [50 50 1750 950];
options.figurePositionDomain = [80 80 1550 900];
options.figurePositionLineBias = [100 100 1250 560];
options.figurePositionLineRaw = [120 80 1250 900];
options.savePNGCopies = false;
options.pngResolutionDPI = 600;
options.codeVersion = ...
    '2026-07-16-local-temp-vector-report-v6';

if isfield(neurometricOptostim, 'options') && ...
        isfield(neurometricOptostim.options, 'sessionLabel')

    options.sessionLabel = ...
        neurometricOptostim.options.sessionLabel;

elseif isfield(neurometricOptostim, 'metadata') && ...
        isfield(neurometricOptostim.metadata, 'sessionLabel')

    options.sessionLabel = ...
        neurometricOptostim.metadata.sessionLabel;
else
    options.sessionLabel = 'neurometricSession';
end

if isfield(neurometricOptostim, 'options') && ...
        isfield(neurometricOptostim.options, 'outputDir')

    options.outputDir = fullfile( ...
        neurometricOptostim.options.outputDir, ...
        'decoder');
else
    repoRoot = fileparts(mfilename('fullpath'));

    options.outputDir = fullfile( ...
        repoRoot, ...
        'outputs', ...
        'neurometric-optostim-decoder');
end

end


function [neurometricOptostim, inputAudit] = ...
    loadNeurometricDecoderInput(neurometricInput)

inputAudit = struct();

if isstruct(neurometricInput)
    neurometricOptostim = neurometricInput;
    inputAudit.inputType = 'structure';
    inputAudit.inputFile = '';
    return;
end

if ischar(neurometricInput) || isstring(neurometricInput)
    inputFile = char(neurometricInput);

    if exist(inputFile, 'file') ~= 2
        error('runNeurometricOptostimDecoder:MissingInputFile', ...
            'Input MAT file does not exist: %s', inputFile);
    end

    loaded = load(inputFile);

    if isfield(loaded, 'neurometricOptostim')
        neurometricOptostim = loaded.neurometricOptostim;
    else
        loadedFields = fieldnames(loaded);
        matchingField = '';

        for fieldIndex = 1:numel(loadedFields)
            candidate = loaded.(loadedFields{fieldIndex});

            if isstruct(candidate) && ...
                    isfield(candidate, 'filteredMaps') && ...
                    isfield(candidate, 'templates') && ...
                    isfield(candidate, 'analysisMask')

                matchingField = loadedFields{fieldIndex};
                break;
            end
        end

        if isempty(matchingField)
            error('runNeurometricOptostimDecoder:MissingResultVariable', ...
                ['No neurometricOptostim-like result structure was ' ...
                 'found in: %s'], inputFile);
        end

        neurometricOptostim = loaded.(matchingField);
    end

    inputAudit.inputType = 'MAT file';
    inputAudit.inputFile = inputFile;
    return;
end

error('runNeurometricOptostimDecoder:InvalidInput', ...
    ['neurometricInput must be either a result structure ' ...
     'or a MAT-file path.']);

end


function validateNeurometricDecoderInput(neurometricOptostim)

requiredTopLevelFields = { ...
    'filteredMaps', ...
    'templates', ...
    'analysisMask', ...
    'stimContrastMatrix', ...
    'conditionDefinitions'};

for fieldIndex = 1:numel(requiredTopLevelFields)
    fieldName = requiredTopLevelFields{fieldIndex};

    if ~isfield(neurometricOptostim, fieldName)
        error('runNeurometricOptostimDecoder:MissingField', ...
            'Missing required result field: %s', fieldName);
    end
end

if ~isfield(neurometricOptostim.filteredMaps, 'columnar')
    error('runNeurometricOptostimDecoder:MissingColumnarMaps', ...
        'filteredMaps.columnar is required.');
end

requiredTemplateFields = { ...
    'G_analysis', ...
    'pca0Current', ...
    'pca90Current'};

for fieldIndex = 1:numel(requiredTemplateFields)
    fieldName = requiredTemplateFields{fieldIndex};

    if ~isfield(neurometricOptostim.templates, fieldName)
        error('runNeurometricOptostimDecoder:MissingTemplateField', ...
            'Missing required template field: %s', fieldName);
    end
end

mapSize = size(neurometricOptostim.filteredMaps.columnar);

if numel(mapSize) < 4
    error('runNeurometricOptostimDecoder:InvalidColumnarMapSize', ...
        ['filteredMaps.columnar must be height x width x ' ...
         'contrast x condition.']);
end

expectedSpatialSize = mapSize(1:2);

if ~isequal(size(neurometricOptostim.analysisMask), ...
        expectedSpatialSize)

    error('runNeurometricOptostimDecoder:MaskSizeMismatch', ...
        'analysisMask does not match the columnar map size.');
end

if ~isequal(size(neurometricOptostim.templates.G_analysis), ...
        expectedSpatialSize)

    error('runNeurometricOptostimDecoder:GaussianSizeMismatch', ...
        'templates.G_analysis does not match the columnar map size.');
end

if ~isequal(size(neurometricOptostim.templates.pca0Current), ...
        expectedSpatialSize) || ...
        ~isequal(size(neurometricOptostim.templates.pca90Current), ...
        expectedSpatialSize)

    error('runNeurometricOptostimDecoder:PCATemplateSizeMismatch', ...
        'PCA decoder templates do not match the columnar map size.');
end

end


function decoder = calculateConditionAverageDecoder( ...
    columnarMaps, templates, analysisMask, ...
    stimContrastMatrix, options)

nContrasts = size(columnarMaps, 3);
nConditions = size(columnarMaps, 4);

spatialWeight = prepareDecoderSpatialWeight( ...
    templates.G_analysis, ...
    analysisMask);

[template0Unit, template0QC] = ...
    prepareSignedDecoderTemplate( ...
        templates.pca0Current, ...
        spatialWeight, ...
        analysisMask, ...
        '0-degree');

[template90Unit, template90QC] = ...
    prepareSignedDecoderTemplate( ...
        templates.pca90Current, ...
        spatialWeight, ...
        analysisMask, ...
        '90-degree');

templateCorrelation = sum( ...
    spatialWeight(:) .* ...
    template0Unit(:) .* ...
    template90Unit(:));

templateCorrelation = min(max(templateCorrelation, -1), 1);

if abs(templateCorrelation) >= ...
        options.templateCorrelationWarning

    warning('runNeurometricOptostimDecoder:TemplateCorrelation', ...
        ['The signed 0-degree and 90-degree PCA templates are strongly ' ...
         'correlated or anticorrelated (r=%g). Signed orientation bias ' ...
         'remains interpretable, but simultaneous activation of both ' ...
         'signed patterns may not be separately identifiable.'], ...
        templateCorrelation);
end

[domainWeight0, domainWeight90, domainWeightQC] = ...
    prepareColumnDomainWeights( ...
        templates, ...
        spatialWeight, ...
        analysisMask);

patternEvidence0 = nan(nContrasts, nConditions);
patternEvidence90 = nan(nContrasts, nConditions);
patternSimilarity0 = nan(nContrasts, nConditions);
patternSimilarity90 = nan(nContrasts, nConditions);
columnarRMS = nan(nContrasts, nConditions);

domainActivation0 = nan(nContrasts, nConditions);
domainActivation90 = nan(nContrasts, nConditions);

for contrastIndex = 1:nContrasts
    for conditionIndex = 1:nConditions

        currentMap = double(columnarMaps( ...
            :, :, contrastIndex, conditionIndex));

        currentMap(~analysisMask | ~isfinite(currentMap)) = 0;

        currentMean = sum( ...
            spatialWeight(:) .* currentMap(:));

        centeredMap = currentMap;
        centeredMap(analysisMask) = ...
            centeredMap(analysisMask) - currentMean;
        centeredMap(~analysisMask) = 0;

        currentRMS = sqrt(sum( ...
            spatialWeight(:) .* centeredMap(:).^2));

        evidence0 = sum( ...
            spatialWeight(:) .* ...
            centeredMap(:) .* ...
            template0Unit(:));

        evidence90 = sum( ...
            spatialWeight(:) .* ...
            centeredMap(:) .* ...
            template90Unit(:));

        patternEvidence0(contrastIndex, conditionIndex) = ...
            evidence0;

        patternEvidence90(contrastIndex, conditionIndex) = ...
            evidence90;

        columnarRMS(contrastIndex, conditionIndex) = ...
            currentRMS;

        if isfinite(currentRMS) && currentRMS > eps
            patternSimilarity0(contrastIndex, conditionIndex) = ...
                evidence0 ./ currentRMS;

            patternSimilarity90(contrastIndex, conditionIndex) = ...
                evidence90 ./ currentRMS;
        end

        domainActivation0(contrastIndex, conditionIndex) = ...
            sum(domainWeight0(analysisMask) .* ...
                currentMap(analysisMask));

        domainActivation90(contrastIndex, conditionIndex) = ...
            sum(domainWeight90(analysisMask) .* ...
                currentMap(analysisMask));
    end
end

patternSimilarity0 = min(max(patternSimilarity0, -1), 1);
patternSimilarity90 = min(max(patternSimilarity90, -1), 1);

%% Signed-pattern representation

patternEvidenceBias = ...
    patternEvidence90 - patternEvidence0;

% Descriptive magnitude in the two projection coordinates. Because the
% signed templates may not be orthogonal, this is not unique neural energy.
patternEvidenceStrength = hypot( ...
    patternEvidence0, patternEvidence90);

patternStrengthFloor = calculateRelativeStrengthFloor( ...
    patternEvidenceStrength, ...
    options.patternStrengthFloorFraction);

patternNormalizedIsStable = ...
    isfinite(patternEvidenceStrength) & ...
    patternEvidenceStrength > max(patternStrengthFloor, eps);

patternNormalizedBias = nan(nContrasts, nConditions);

patternBiasDenominator = ...
    abs(patternEvidence90) + abs(patternEvidence0);

patternNormalizedBias(patternNormalizedIsStable) = ...
    patternEvidenceBias(patternNormalizedIsStable) ./ ...
    max(patternBiasDenominator(patternNormalizedIsStable), eps);

patternNormalizedBias = ...
    min(max(patternNormalizedBias, -1), 1);

%% Separate nonnegative column-domain representation

domainDifference = ...
    domainActivation90 - domainActivation0;

domainStrength = hypot( ...
    domainActivation0, domainActivation90);

domainStrengthFloor = calculateRelativeStrengthFloor( ...
    domainStrength, ...
    options.domainStrengthFloorFraction);

domainNormalizedIsStable = ...
    isfinite(domainStrength) & ...
    domainStrength > max(domainStrengthFloor, eps);

domainNormalizedBias = nan(nContrasts, nConditions);

domainBiasDenominator = ...
    abs(domainActivation90) + abs(domainActivation0);

domainNormalizedBias(domainNormalizedIsStable) = ...
    domainDifference(domainNormalizedIsStable) ./ ...
    max(domainBiasDenominator(domainNormalizedIsStable), eps);

domainNormalizedBias = ...
    min(max(domainNormalizedBias, -1), 1);

positiveDomain0 = max(domainActivation0, 0);
positiveDomain90 = max(domainActivation90, 0);
positiveDomainSum = positiveDomain0 + positiveDomain90;

totalPositiveDomainStrength = hypot( ...
    positiveDomain0, positiveDomain90);

% Raw coactivation is high only when both positive domain readouts are high.
rawCoactivation = sqrt( ...
    positiveDomain0 .* positiveDomain90);

coactivationIsStable = ...
    isfinite(positiveDomainSum) & ...
    positiveDomainSum > max(domainStrengthFloor, eps);

normalizedCoactivation = nan(nContrasts, nConditions);

normalizedCoactivation(coactivationIsStable) = ...
    2 .* rawCoactivation(coactivationIsStable) ./ ...
    positiveDomainSum(coactivationIsStable);

normalizedCoactivation = ...
    min(max(normalizedCoactivation, 0), 1);

%% Visual-only benchmark checks

benchmark = calculateVisualOnlyBenchmark( ...
    patternEvidenceBias, ...
    domainDifference, ...
    stimContrastMatrix);

%% Package

decoder = struct();

decoder.pattern = struct();
decoder.pattern.evidence0 = patternEvidence0;
decoder.pattern.evidence90 = patternEvidence90;
decoder.pattern.evidenceBias = patternEvidenceBias;
decoder.pattern.evidenceStrength = patternEvidenceStrength;
decoder.pattern.similarity0 = patternSimilarity0;
decoder.pattern.similarity90 = patternSimilarity90;
decoder.pattern.normalizedBias = patternNormalizedBias;
decoder.pattern.normalizedIsStable = patternNormalizedIsStable;
decoder.pattern.strengthFloor = patternStrengthFloor;
decoder.pattern.columnarRMS = columnarRMS;

decoder.domain = struct();
decoder.domain.activation0 = domainActivation0;
decoder.domain.activation90 = domainActivation90;
decoder.domain.difference = domainDifference;
decoder.domain.strength = domainStrength;
decoder.domain.normalizedBias = domainNormalizedBias;
decoder.domain.normalizedIsStable = domainNormalizedIsStable;
decoder.domain.strengthFloor = domainStrengthFloor;
decoder.domain.positiveActivation0 = positiveDomain0;
decoder.domain.positiveActivation90 = positiveDomain90;
decoder.domain.totalPositiveStrength = ...
    totalPositiveDomainStrength;
decoder.domain.rawCoactivation = rawCoactivation;
decoder.domain.normalizedCoactivation = ...
    normalizedCoactivation;
decoder.domain.coactivationIsStable = ...
    coactivationIsStable;

decoder.templates = struct();
decoder.templates.spatialWeight = spatialWeight;
decoder.templates.signed0Unit = template0Unit;
decoder.templates.signed90Unit = template90Unit;
decoder.templates.domainWeight0 = domainWeight0;
decoder.templates.domainWeight90 = domainWeight90;

decoder.qc = struct();
decoder.qc.templateCorrelation = templateCorrelation;
decoder.qc.template0 = template0QC;
decoder.qc.template90 = template90QC;
decoder.qc.domainWeights = domainWeightQC;
decoder.qc.visualOnlyBenchmark = benchmark;

decoder.method = struct();
decoder.method.patternEvidence = ...
    ['Weighted projection of each condition-average 0.8-3 cycles/mm ' ...
     'map onto mean-centered, unit-weighted-RMS signed PCA-denoised ' ...
     'flash templates.'];

decoder.method.patternBias = ...
    ['evidence90 - evidence0; negative means more 0-degree-like and ' ...
     'positive means more 90-degree-like.'];

decoder.method.patternNormalizedBias = ...
    ['(evidence90 - evidence0) / ' ...
     '(|evidence90| + |evidence0|).'];

decoder.method.domainActivation = ...
    ['Weighted average of the condition columnar map within separate ' ...
     'nonnegative flash-derived 0-degree and 90-degree domains.'];

decoder.method.coactivation = ...
    ['sqrt(max(domain0,0) * max(domain90,0)); high only when both ' ...
     'column-domain activations are positive and large.'];

end


function spatialWeight = prepareDecoderSpatialWeight( ...
    gaussianMap, analysisMask)

spatialWeight = double(gaussianMap);
spatialWeight(~analysisMask | ~isfinite(spatialWeight)) = 0;
spatialWeight = max(spatialWeight, 0);

weightSum = sum(spatialWeight(:));

if ~isfinite(weightSum) || weightSum <= 0
    error('runNeurometricOptostimDecoder:InvalidSpatialWeight', ...
        'The flash-derived Gaussian spatial weight is invalid.');
end

spatialWeight = spatialWeight ./ weightSum;

end


function [templateUnit, templateQC] = ...
    prepareSignedDecoderTemplate( ...
        templateMap, spatialWeight, ...
        analysisMask, templateName)

templateMap = double(templateMap);
templateMap(~analysisMask | ~isfinite(templateMap)) = 0;

templateMean = sum( ...
    spatialWeight(:) .* templateMap(:));

templateCentered = templateMap;
templateCentered(analysisMask) = ...
    templateCentered(analysisMask) - templateMean;
templateCentered(~analysisMask) = 0;

templateRMS = sqrt(sum( ...
    spatialWeight(:) .* templateCentered(:).^2));

if ~isfinite(templateRMS) || templateRMS <= eps
    error('runNeurometricOptostimDecoder:InvalidSignedTemplate', ...
        '%s signed PCA template has zero weighted RMS.', ...
        templateName);
end

templateUnit = templateCentered ./ templateRMS;

templateQC = struct();
templateQC.weightedMean = templateMean;
templateQC.weightedRMS = templateRMS;
templateQC.minimum = min(templateCentered(analysisMask));
templateQC.maximum = max(templateCentered(analysisMask));

end


function [weight0, weight90, qc] = ...
    prepareColumnDomainWeights( ...
        templates, spatialWeight, analysisMask)

if isfield(templates, 'W_COL0') && ...
        isfield(templates, 'W_COL90') && ...
        ~isempty(templates.W_COL0) && ...
        ~isempty(templates.W_COL90)

    weight0 = double(templates.W_COL0);
    weight90 = double(templates.W_COL90);
else
    preference0 = max(double(templates.pca0Current), 0);
    preference90 = max(double(templates.pca90Current), 0);

    weight0 = spatialWeight .* preference0;
    weight90 = spatialWeight .* preference90;
end

weight0(~analysisMask | ~isfinite(weight0)) = 0;
weight90(~analysisMask | ~isfinite(weight90)) = 0;

weight0 = max(weight0, 0);
weight90 = max(weight90, 0);

sum0 = sum(weight0(analysisMask));
sum90 = sum(weight90(analysisMask));

if ~isfinite(sum0) || sum0 <= 0 || ...
        ~isfinite(sum90) || sum90 <= 0

    error('runNeurometricOptostimDecoder:InvalidDomainWeights', ...
        'The 0-degree or 90-degree domain weight is empty.');
end

weight0 = weight0 ./ sum0;
weight90 = weight90 ./ sum90;

qc = struct();
qc.sum0 = sum(weight0(analysisMask));
qc.sum90 = sum(weight90(analysisMask));
qc.softOverlap = sum(min( ...
    weight0(analysisMask), ...
    weight90(analysisMask)));
qc.correlation = safeDecoderCorrelation( ...
    weight0(analysisMask), ...
    weight90(analysisMask));

end


function strengthFloor = calculateRelativeStrengthFloor( ...
    strengthValues, floorFraction)

finiteStrength = strengthValues(isfinite(strengthValues));

if isempty(finiteStrength)
    strengthFloor = 0;
else
    strengthFloor = floorFraction .* max(finiteStrength);
end

end


function benchmark = calculateVisualOnlyBenchmark( ...
    patternBias, domainBias, stimContrastMatrix)

benchmark = struct();

if size(patternBias, 2) < 4 || ...
        size(stimContrastMatrix, 2) < 4

    benchmark.status = ...
        'Not calculated: expected six-condition layout was unavailable.';
    return;
end

v0Contrast = stimContrastMatrix(:,1);
v90Contrast = stimContrastMatrix(:,4);

v0Rows = isfinite(v0Contrast) & v0Contrast > 0;
v90Rows = isfinite(v90Contrast) & v90Contrast > 0;

patternV0Correct = patternBias(v0Rows,1) < 0;
patternV90Correct = patternBias(v90Rows,4) > 0;

domainV0Correct = domainBias(v0Rows,1) < 0;
domainV90Correct = domainBias(v90Rows,4) > 0;

benchmark.patternV0Correct = patternV0Correct;
benchmark.patternV90Correct = patternV90Correct;
benchmark.domainV0Correct = domainV0Correct;
benchmark.domainV90Correct = domainV90Correct;

benchmark.patternAccuracy = meanFiniteLogical([ ...
    patternV0Correct(:); ...
    patternV90Correct(:)]);

benchmark.domainAccuracy = meanFiniteLogical([ ...
    domainV0Correct(:); ...
    domainV90Correct(:)]);

benchmark.status = ...
    ['Uses nonzero-contrast visual-only V0 and V90 cells as a sign ' ...
     'sanity check; it is not cross-validated decoding accuracy.'];

end


function outputFiles = plotNeurometricDecoderQC( ...
    decoderResult, neurometricOptostim, options)

outputFiles = struct();

[cmapDiverging, cmapPositive] = ...
    getNeurometricDecoderColormaps();

conditionLabels = decoderConditionLabels( ...
    size(decoderResult.pattern.evidence0, 2));

rowLabels = decoderContrastRowLabels( ...
    neurometricOptostim.stimContrastMatrix);

%% Figure 1: signed-pattern decoder heatmaps

figPattern = figure( ...
    'Name', ...
    'Neurometric optostim signed-pattern decoder', ...
    'Color', 'w', ...
    'Position', ...
    options.figurePositionPattern);

patternEvidencePairLimit = finiteMaxAbs([ ...
    decoderResult.pattern.evidence0(:); ...
    decoderResult.pattern.evidence90(:)]);

patternBiasLimit = finiteMaxAbs( ...
    decoderResult.pattern.evidenceBias(:));

patternStrengthLimit = finiteMaxPositive( ...
    decoderResult.pattern.evidenceStrength(:));

columnarRMSLimit = finiteMaxPositive( ...
    decoderResult.pattern.columnarRMS(:));

plotDecoderPanel( ...
    subplot(2,4,1), ...
    decoderResult.pattern.evidence0, ...
    'Raw signed-pattern evidence: 0 degrees', ...
    [-patternEvidencePairLimit patternEvidencePairLimit], ...
    cmapDiverging, ...
    conditionLabels, rowLabels);

plotDecoderPanel( ...
    subplot(2,4,2), ...
    decoderResult.pattern.evidence90, ...
    'Raw signed-pattern evidence: 90 degrees', ...
    [-patternEvidencePairLimit patternEvidencePairLimit], ...
    cmapDiverging, ...
    conditionLabels, rowLabels);

plotDecoderPanel( ...
    subplot(2,4,3), ...
    decoderResult.pattern.evidenceBias, ...
    'Raw orientation bias: 90 minus 0', ...
    [-patternBiasLimit patternBiasLimit], ...
    cmapDiverging, ...
    conditionLabels, rowLabels);

plotDecoderPanel( ...
    subplot(2,4,4), ...
    decoderResult.pattern.evidenceStrength, ...
    'Raw signed-pattern strength', ...
    [0 patternStrengthLimit], ...
    cmapPositive, ...
    conditionLabels, rowLabels);

plotDecoderPanel( ...
    subplot(2,4,5), ...
    decoderResult.pattern.similarity0, ...
    'Pattern similarity to 0 degrees', ...
    [-1 1], ...
    cmapDiverging, ...
    conditionLabels, rowLabels);

plotDecoderPanel( ...
    subplot(2,4,6), ...
    decoderResult.pattern.similarity90, ...
    'Pattern similarity to 90 degrees', ...
    [-1 1], ...
    cmapDiverging, ...
    conditionLabels, rowLabels);

