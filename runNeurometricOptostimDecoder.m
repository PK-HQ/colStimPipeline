values = values(isfinite(values));

if isempty(values)
    value = 1;
else
    value = max(values);

    if value <= 0
        value = 1;
    end
end

end


function r = safeDecoderCorrelation(x, y)

x = double(x(:));
y = double(y(:));

valid = isfinite(x) & isfinite(y);
x = x(valid);
y = y(valid);

if numel(x) < 2 || ...
        std(x) <= eps || ...
        std(y) <= eps

    r = NaN;
    return;
end

correlationMatrix = corrcoef(x, y);
r = correlationMatrix(1,2);

end


function output = mergeStructFields(base, override)

output = base;

if isempty(override)
    return;
end

overrideFields = fieldnames(override);

for fieldIndex = 1:numel(overrideFields)
    output.(overrideFields{fieldIndex}) = ...
        override.(overrideFields{fieldIndex});
end

end


