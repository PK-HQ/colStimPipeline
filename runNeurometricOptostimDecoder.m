function rowLabels = decoderContrastRowLabels( ...
    stimContrastMatrix)

nRows = size(stimContrastMatrix, 1);
rowLabels = cell(nRows, 1);

for rowIndex = 1:nRows
    baselineColumns = intersect([1 4], ...
        1:size(stimContrastMatrix,2));

    optoColumns = intersect([2 3 5 6], ...
        1:size(stimContrastMatrix,2));

    baselineCandidates = ...
        stimContrastMatrix(rowIndex, baselineColumns);

    optoCandidates = ...
        stimContrastMatrix(rowIndex, optoColumns);

    baselineCandidates = ...
        baselineCandidates(isfinite(baselineCandidates));

    optoCandidates = ...
        optoCandidates(isfinite(optoCandidates));

    if isempty(baselineCandidates)
        baselineContrast = NaN;
    else
        baselineContrast = baselineCandidates(1);
    end

    if isempty(optoCandidates)
        optoContrast = NaN;
    else
        optoContrast = optoCandidates(1);
    end

    if isfinite(baselineContrast) && ...
            isfinite(optoContrast)

        rowLabels{rowIndex} = sprintf('%g / %g', ...
            baselineContrast, optoContrast);

    elseif isfinite(baselineContrast)
        rowLabels{rowIndex} = sprintf('%g / -', ...
            baselineContrast);

    elseif isfinite(optoContrast)
        rowLabels{rowIndex} = sprintf('- / %g', ...
            optoContrast);
    else
        rowLabels{rowIndex} = ...
            sprintf('Rank %d', rowIndex);
    end
end

end


function reportContext = ...
    prepareDecoderPDFReport(options)
%PREPAREDECODERPDFREPORT Create a unique local staging directory.
%
% PDF pages are never written directly into the network output directory.
% Existing reports can therefore remain open in Acrobat, Edge, or another
% viewer without locking the next run's temporary pages. The completed
% four-page report is copied to a new timestamped output filename only
% after all pages have been created and merged successfully.

reportContext = struct();

reportContext.tempDir = tempname(tempdir);

[mkdirSucceeded, mkdirMessage] = ...
    mkdir(reportContext.tempDir);

if ~mkdirSucceeded
    error('runNeurometricOptostimDecoder:TempReportDirectoryFailed', ...
        ['Could not create the local decoder report staging directory:\n' ...
         '%s\n\n%s'], ...
        reportContext.tempDir, ...
        mkdirMessage);
end

reportContext.localMergedPDF = fullfile( ...
    reportContext.tempDir, ...
    'neurometricOptostimDecoder_merged.pdf');

runStamp = datestr(now, ...
    'yyyymmdd_HHMMSS');

reportContext.finalPDF = fullfile( ...
    options.outputDir, ...
    sprintf('%s_neurometricOptostimDecoder_figures_%s.pdf', ...
        options.sessionLabel, ...
        runStamp));

% Resolve the extremely unlikely case of two runs beginning in one second.
suffixIndex = 1;

while exist(reportContext.finalPDF, 'file') == 2
    reportContext.finalPDF = fullfile( ...
        options.outputDir, ...
        sprintf('%s_neurometricOptostimDecoder_figures_%s_%02d.pdf', ...
            options.sessionLabel, ...
            runStamp, ...
            suffixIndex));

    suffixIndex = suffixIndex + 1;
end

end


function savedFiles = saveDecoderFigurePage( ...
    fig, options, suffix, pageNumber, ...
    reportContext)
%SAVEDECODERFIGUREPAGE Save one complete figure and one vector PDF page.
%
% The report PDF is written directly from the original MATLAB figure using
% the Painters renderer. There is no PNG-to-PDF round trip, so increasing
% PNG resolution cannot slow or blur the report. Text, axes, lines,
% markers, legends, and annotations remain vector objects. The small
% heatmap image objects are embedded without resampling the entire page.

savedFiles = struct();

set(fig, 'Color', 'w');
drawnow;

%% Editable MATLAB FIG

savedFiles.fig = fullfile( ...
    options.outputDir, ...
    sprintf('%s_%s.fig', ...
        options.sessionLabel, ...
        suffix));

savefig(fig, savedFiles.fig);

%% Optional high-resolution PNG copy
%
% Disabled by default because it is not used to build the PDF report.
% Enable userOptions.savePNGCopies only when a separate raster file is
% actually needed.

savedFiles.png = '';

if isfield(options, 'savePNGCopies') && ...
        options.savePNGCopies

    savedFiles.png = fullfile( ...
        options.outputDir, ...
        sprintf('%s_%s.png', ...
            options.sessionLabel, ...
            suffix));

    saveDecoderOptionalPNG( ...
        fig, ...
        savedFiles.png, ...
        options.pngResolutionDPI);
end

%% Explicitly numbered direct vector PDF page

savedFiles.pdfPage = fullfile( ...
    reportContext.tempDir, ...
    sprintf('decoderPdfPage_%02d_%s.pdf', ...
        pageNumber, ...
        suffix));

saveDecoderVectorPDFPage( ...
    fig, ...
    savedFiles.pdfPage);

end


function saveDecoderOptionalPNG( ...
    fig, pngPath, resolutionDPI)
%SAVEDECODEROPTIONALPNG Save a separate raster copy when explicitly asked.

if exist(pngPath, 'file') == 2
    delete(pngPath);
end

oldState = captureDecoderPrintState(fig);

set(fig, ...
    'Color', 'w', ...
    'Renderer', 'opengl', ...
    'PaperPositionMode', 'auto', ...
    'InvertHardcopy', 'off');

drawnow;

try
    print(fig, ...
        pngPath, ...
        '-dpng', ...
        '-opengl', ...
        sprintf('-r%d', resolutionDPI));
catch ME
    restoreDecoderPrintState(fig, oldState);
    rethrow(ME);
end

restoreDecoderPrintState(fig, oldState);

if exist(pngPath, 'file') ~= 2
    error('runNeurometricOptostimDecoder:PNGSaveFailed', ...
        'The optional decoder PNG was not created: %s', ...
        pngPath);
end

end


function saveDecoderVectorPDFPage( ...
    fig, pdfPath)
%SAVEDECODERVECTORPDFPAGE Save one complete landscape vector PDF page.
%
% The page is fixed at 11 x 8.5 inches. The figure aspect ratio is
% preserved and centered. Painters is used directly on the original
% figure, avoiding both screen-resolution capture and OpenGL page
% rasterization.

if exist(pdfPath, 'file') == 2
    delete(pdfPath);
end

oldState = captureDecoderPrintState(fig);

set(fig, ...
    'Color', 'w', ...
    'Units', 'pixels');

figurePosition = get(fig, 'Position');

figureWidth = max(double(figurePosition(3)), 1);
figureHeight = max(double(figurePosition(4)), 1);
figureAspect = figureWidth ./ figureHeight;

pageWidth = 11;
pageHeight = 8.5;
margin = 0.25;

availableWidth = pageWidth - 2 .* margin;
availableHeight = pageHeight - 2 .* margin;
availableAspect = availableWidth ./ availableHeight;

if figureAspect >= availableAspect
    printedWidth = availableWidth;
    printedHeight = printedWidth ./ figureAspect;
else
    printedHeight = availableHeight;
    printedWidth = printedHeight .* figureAspect;
end

printedLeft = 0.5 .* ...
    (pageWidth - printedWidth);

printedBottom = 0.5 .* ...
    (pageHeight - printedHeight);

set(fig, ...
    'Renderer', 'painters', ...
    'PaperUnits', 'inches', ...
    'PaperSize', [pageWidth pageHeight], ...
    'PaperPosition', [ ...
        printedLeft, ...
        printedBottom, ...
        printedWidth, ...
        printedHeight], ...
    'PaperPositionMode', 'manual', ...
    'PaperOrientation', 'portrait', ...
    'InvertHardcopy', 'off');

drawnow;

try
    print(fig, ...
        pdfPath, ...
        '-dpdf', ...
        '-painters');
catch ME
    restoreDecoderPrintState(fig, oldState);
    rethrow(ME);
end

restoreDecoderPrintState(fig, oldState);

if exist(pdfPath, 'file') ~= 2
    error('runNeurometricOptostimDecoder:PDFPageSaveFailed', ...
        'The direct vector PDF page was not created: %s', ...
        pdfPath);
end

end


