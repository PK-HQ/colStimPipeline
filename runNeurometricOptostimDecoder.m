function plotDecoderConditionTrio( ...
    ax, stimContrastMatrix, metricMatrix, ...
    conditionIndices, conditionLabels, ...
    lineColors, panelTitle, yLabelText, ...
    yLimits, addBiasDirectionLabels)

hold(ax, 'on');

lineHandles = gobjects(1, numel(conditionIndices));

for lineIndex = 1:numel(conditionIndices)
    conditionIndex = conditionIndices(lineIndex);

    xValues = double( ...
        stimContrastMatrix(:,conditionIndex));

    yValues = double( ...
        metricMatrix(:,conditionIndex));

    valid = isfinite(xValues) & isfinite(yValues);

    xValues = xValues(valid);
    yValues = yValues(valid);

    [xValues, sortOrder] = sort(xValues);
    yValues = yValues(sortOrder);

    lineHandles(lineIndex) = plot( ...
        ax, ...
        xValues, ...
        yValues, ...
        '-o', ...
        'Color', lineColors{lineIndex}, ...
        'MarkerFaceColor', lineColors{lineIndex}, ...
        'MarkerEdgeColor', lineColors{lineIndex}, ...
        'LineWidth', 2, ...
        'MarkerSize', 6);
end

allX = double( ...
    stimContrastMatrix(:,conditionIndices));

allX = allX(isfinite(allX));

if isempty(allX)
    xLimits = [0 1];
else
    xMinimum = min(allX);
    xMaximum = max(allX);

    if xMaximum <= xMinimum
        xLimits = [xMinimum - 0.5, xMaximum + 0.5];
    else
        xPadding = 0.03 .* ...
            (xMaximum - xMinimum);

        xLimits = [ ...
            max(0, xMinimum - xPadding), ...
            xMaximum + xPadding];
    end
end

plot(ax, ...
    xLimits, ...
    [0 0], ...
    '--', ...
    'Color', [0.45 0.45 0.45], ...
    'LineWidth', 1, ...
    'HandleVisibility', 'off');

xlim(ax, xLimits);
ylim(ax, yLimits);

xlabel(ax, 'Stimulus contrast (%)');
ylabel(ax, yLabelText);
title(ax, panelTitle);

legend(ax, ...
    lineHandles, ...
    conditionLabels, ...
    'Location', 'best', ...
    'Interpreter', 'none');

set(ax, ...
    'Box', 'off', ...
    'TickDir', 'out', ...
    'FontSize', 10);

if addBiasDirectionLabels
    text(ax, ...
        0.02, 0.97, ...
        'More 90-degree-like', ...
        'Units', 'normalized', ...
        'HorizontalAlignment', 'left', ...
        'VerticalAlignment', 'top', ...
        'FontWeight', 'bold');

    text(ax, ...
        0.02, 0.03, ...
        'More 0-degree-like', ...
        'Units', 'normalized', ...
        'HorizontalAlignment', 'left', ...
        'VerticalAlignment', 'bottom', ...
        'FontWeight', 'bold');
end

hold(ax, 'off');

end


