function pdfPath = finalizeDecoderMultiPagePDF( ...
    pagePaths, options, reportContext)
%FINALIZEDECODERMULTIPAGEPDF Merge four local pages and publish atomically.
%
% The four vector pages and the merged report are created on the local
% system drive. Only the completed report is copied to the network output
% directory. The final filename is timestamped, so an older PDF can remain
% open without causing permission-denied errors.

expectedPageCount = 4;

if numel(pagePaths) ~= expectedPageCount
    cleanupDecoderReportTempDirectory( ...
        reportContext.tempDir);

    error('runNeurometricOptostimDecoder:WrongPDFPageCount', ...
        'Expected %d decoder PDF pages, but received %d.', ...
        expectedPageCount, ...
        numel(pagePaths));
end

for pageIndex = 1:expectedPageCount
    if exist(pagePaths{pageIndex}, 'file') ~= 2
        error('runNeurometricOptostimDecoder:MissingPDFPage', ...
            ['Decoder PDF page %d is missing:\n%s\n\n' ...
             'The local staging directory was retained:\n%s'], ...
            pageIndex, ...
            pagePaths{pageIndex}, ...
            reportContext.tempDir);
    end
end

ghostscriptPath = ...
    findDecoderGhostscriptExecutable();

if exist(reportContext.localMergedPDF, 'file') == 2
    delete(reportContext.localMergedPDF);
end

inputArguments = '';

for pageIndex = 1:expectedPageCount
    inputArguments = sprintf( ...
        '%s "%s"', ...
        inputArguments, ...
        pagePaths{pageIndex});
end

ghostscriptCommand = sprintf([ ...
    '"%s" ' ...
    '-q ' ...
    '-dNOPAUSE ' ...
    '-dBATCH ' ...
    '-dNOSAFER ' ...
    '-sDEVICE=pdfwrite ' ...
    '-dAutoRotatePages=/None ' ...
    '-dCompatibilityLevel=1.4 ' ...
    '-dDetectDuplicateImages=false ' ...
    '-dDownsampleColorImages=false ' ...
    '-dDownsampleGrayImages=false ' ...
    '-dDownsampleMonoImages=false ' ...
    '-sOutputFile="%s"%s'], ...
    ghostscriptPath, ...
    reportContext.localMergedPDF, ...
    inputArguments);

[mergeStatus, mergeOutput] = ...
    system(ghostscriptCommand);

if mergeStatus ~= 0 || ...
        exist(reportContext.localMergedPDF, 'file') ~= 2

    error('runNeurometricOptostimDecoder:PDFMergeFailed', ...
        ['Direct local Ghostscript merge failed.\n\n' ...
         'Command output:\n%s\n\n' ...
         'The four local PDF pages were retained in:\n%s'], ...
        mergeOutput, ...
        reportContext.tempDir);
end

actualPageCount = countDecoderPDFPages( ...
    ghostscriptPath, ...
    reportContext.localMergedPDF);

if isfinite(actualPageCount) && ...
        actualPageCount ~= expectedPageCount

    error('runNeurometricOptostimDecoder:WrongMergedPDFPageCount', ...
        ['The locally merged report contains %d pages instead of %d.\n' ...
         'The local staging directory was retained:\n%s'], ...
        actualPageCount, ...
        expectedPageCount, ...
        reportContext.tempDir);
end

% Copy to a new output filename. No existing network file is deleted or
% overwritten, so open PDF viewers cannot block this operation.
[copySucceeded, copyMessage] = copyfile( ...
    reportContext.localMergedPDF, ...
    reportContext.finalPDF);

if ~copySucceeded || ...
        exist(reportContext.finalPDF, 'file') ~= 2

    error('runNeurometricOptostimDecoder:PDFPublishFailed', ...
        ['The completed local decoder report could not be copied to:\n' ...
         '%s\n\n%s\n\n' ...
         'The complete local report remains available at:\n%s'], ...
        reportContext.finalPDF, ...
        copyMessage, ...
        reportContext.localMergedPDF);
end

pdfPath = reportContext.finalPDF;

if isfinite(actualPageCount)
    fprintf(['Saved decoder PDF report with %d verified vector pages:\n' ...
        '  %s\n'], ...
        actualPageCount, ...
        pdfPath);
else
    fprintf(['Saved decoder PDF report from four explicit vector pages:\n' ...
        '  %s\n'], ...
        pdfPath);
end

cleanupDecoderReportTempDirectory( ...
    reportContext.tempDir);

end


function cleanupDecoderReportTempDirectory( ...
    tempDirectory)

if isempty(tempDirectory) || ...
        exist(tempDirectory, 'dir') ~= 7

    return;
end

try
    rmdir(tempDirectory, 's');
catch
    % Cleanup is noncritical. Do not turn a successfully saved report into
    % a failed analysis merely because Windows retained a transient handle.
end

end


function ghostscriptPath = ...
    findDecoderGhostscriptExecutable()

candidateExecutables = { ...
    'gswin64c.exe', ...
    'gswin32c.exe'};

ghostscriptPath = '';

for candidateIndex = 1:numel(candidateExecutables)
    [whereStatus, whereOutput] = system( ...
        sprintf('where %s', ...
            candidateExecutables{candidateIndex}));

    if whereStatus ~= 0
        continue;
    end

    outputLines = regexp( ...
        strtrim(whereOutput), ...
        '\r\n|\n|\r', ...
        'split');

    for lineIndex = 1:numel(outputLines)
        candidatePath = strtrim(outputLines{lineIndex});

        if exist(candidatePath, 'file') == 2
            ghostscriptPath = candidatePath;
            return;
        end
    end
end

error('runNeurometricOptostimDecoder:GhostscriptNotFound', ...
    ['Neither gswin64c.exe nor gswin32c.exe was found on the ' ...
     'Windows PATH.']);

end


function pageCount = countDecoderPDFPages( ...
    ghostscriptPath, pdfPath)
%COUNTDECODERPDFPAGES Best-effort page-count verification.
%
% Verification is deliberately nonessential to report generation. The
% merged PDF has already been created from four explicit input files.
%
% First try pdfinfo when it is installed. Otherwise ask Ghostscript to
% inspect the trusted local PDF with -dNOSAFER. Ghostscript 10 enables
% SAFER by default, which was why the previous verification command could
% not open the newly created PDF even though the merge itself succeeded.

pageCount = NaN;

%% Preferred counter: pdfinfo

[whereStatus, whereOutput] = ...
    system('where pdfinfo.exe');

if whereStatus == 0
    outputLines = regexp( ...
        strtrim(whereOutput), ...
        '\r\n|\n|\r', ...
        'split');

    if ~isempty(outputLines)
        pdfInfoPath = strtrim(outputLines{1});

        if exist(pdfInfoPath, 'file') == 2
            [infoStatus, infoOutput] = system( ...
                sprintf('"%s" "%s"', ...
                    pdfInfoPath, ...
                    pdfPath));

            if infoStatus == 0
                pageToken = regexp( ...
                    infoOutput, ...
                    'Pages:\s*(\d+)', ...
                    'tokens', ...
                    'once');

                if ~isempty(pageToken)
                    pageCount = str2double( ...
                        pageToken{1});
                    return;
                end
            end
        end
    end
end

%% Fallback counter: Ghostscript

postScriptPath = strrep(pdfPath, '\', '/');
postScriptPath = strrep(postScriptPath, '(', '\(');
postScriptPath = strrep(postScriptPath, ')', '\)');

countCommand = sprintf([ ...
    '"%s" -q -dNODISPLAY -dNOSAFER ' ...
    '-c "(%s) (r) file runpdfbegin pdfpagecount = quit"'], ...
    ghostscriptPath, ...
    postScriptPath);

[countStatus, countOutput] = ...
    system(countCommand);

if countStatus ~= 0
    return;
end

numericTokens = regexp( ...
    strtrim(countOutput), ...
    '\d+', ...
    'match');

if ~isempty(numericTokens)
    pageCount = str2double( ...
        numericTokens{end});
end

end


